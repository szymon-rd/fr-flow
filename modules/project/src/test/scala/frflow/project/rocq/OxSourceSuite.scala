package frflow.project.rocq

import frflow.core.threads.Datum
import frflow.dsl.compiled.source.{CountSource, ReadSource}
import frflow.proof.rocq.threads.PrintData
import java.nio.file.Files
import java.nio.file.Path

/** The whole of Ox 1.1.0 (`com.softwaremill.ox:core_3:1.1.0`), read from the TASTy of its jar into Rocq as the
  * trees the compiler typed (`modules/proof/rocq/FrFlow/Scala/Tree.v`), a Rocq file for each TASTy file, nothing
  * chosen or left out. `FRFLOW_ROCQ_WRITE=1` writes the files anew.
  */
class OxSourceSuite extends munit.FunSuite:
  override val munitTimeout = scala.concurrent.duration.Duration(60, "min")

  private val out = Path.of(sys.env.getOrElse("FRFLOW_OX_TREES", "examples/ox/rocq/Ox/Tree"))
  private lazy val read: List[(String, Datum)] = ReadSource(classOf[_root_.ox.Ox])
  private def named(path: String): String = path.stripSuffix(".tasty").replaceAll("[^A-Za-z0-9]", "_")
  private lazy val files: List[(String, String)] = read.map((path, d) =>
    s"${named(path)}.v" -> PrintData.file(named(path), s"$path of ${OxUnit.jar}, as the tree it holds. " +
      "Generated by FrFlow (`frflow.dsl.compiled.source`): do not edit.", d))

  /** The constructors of `tree`: the forms counted (those of `sym`, `ty` and `const` are not trees). */
  private val forms = Set("Ident", "Select", "SelectOuter", "This", "Super", "Literal", "New", "Apply", "TypeApply",
    "NamedArg", "Typed", "Assign", "Block", "Closure", "If", "Match", "SummonFrom", "Try", "Return", "While",
    "Repeated", "Inlined", "ValDef", "DefDef", "TypeDef", "ClassDef", "PackageClause", "Imported", "Exported",
    "TypeTree", "CaseDef", "Bind", "Unapply", "Alternatives", "TypeTest", "Wildcard", "Other")

  private def others(d: Datum): Int = d.constructors.count(_ == "Other")

  test("every tree of Ox's TASTy is read, once: the compiler's own traversal counts the same of each form") {
    val mine = read.flatMap(_._2.constructors).filter(forms).groupBy(identity).view.mapValues(_.size).toMap
    assertEquals(mine, CountSource(classOf[_root_.ox.Ox]))
    assertEquals(read.map(_._2).map(others).sum, 0)
    assertEquals((read.size, mine.values.sum), (116, 38939))
  }

  test("the generator prints the files that are kept") {
    if sys.env.contains("FRFLOW_ROCQ_WRITE") then
      Files.createDirectories(out)
      files.foreach((name, text) => Files.writeString(out.resolve(name), text))
    files.foreach((name, text) => assertEquals(text, Files.readString(out.resolve(name)), name))
  }

  /** What Ox's trees refer to outside Ox: each definition read or called whose owner is not inside `ox`. */
  private lazy val surface: List[List[String]] =
    read.flatMap((_, d) => OxSource.mentioned(d)).distinct.filterNot(m => OxSource.within("ox", m.head)).sorted(
      using Ordering.Implicits.seqOrdering[List, String])

  test("the generator prints the files that are kept: the index, and what Ox takes from outside") {
    val kept = List("All.v" -> OxSource.index(files.map(_._1.stripSuffix(".v"))), "Surface.v" ->
      OxSource.surface(surface))
    if sys.env.contains("FRFLOW_ROCQ_WRITE") then kept.foreach((n, t) => Files.writeString(out.resolve(n), t))
    kept.foreach((name, text) => assertEquals(text, Files.readString(out.resolve(name)), name))
    assertEquals(surface.size, 513)
  }

  /** `Assumed.v`'s rows under a contract: a member of the JDK (its class, a companion's `$` apart, and its
    * name) and the operations of `Jdk.v` it is said to be.
    */
  private def contracts: Map[(String, String), Set[String]] =
    val row = """\(Member "([^"]*)" "([^"]*)" "[^"]*", Contract "([^"]*)"\)""".r
    row.findAllMatchIn(Files.readString(out.resolve("Assumed.v"))).toList
      .groupMapReduce(m => (m.group(1).stripSuffix("$"), m.group(2)))(m => m.group(3).split(", ").toSet)(_ ++ _)

  test("the reader of thread programs calls a JDK method the operation `Assumed.v` gives it") {
    val read = frflow.dsl.compiled.threads.known.Jdk.methods.view.mapValues(_.name).toMap
    val differing = read.toList.flatMap((method, op) =>
      contracts.get(method).filterNot(_.contains(op)).map(ops => s"$method: $op, not ${ops.mkString(", ")}"))
    assertEquals(differing, Nil)
    assertEquals(read.keySet.filterNot(contracts.contains), Set(("java.util.concurrent.atomic.AtomicReference", "get")))
  }

  /** The files kept by hand beside the trees, each checked by Rocq against what it computes from them. */
  private val checked = List("All.v", "Surface.v", "Kernel.v", "Assumed.v", "Memory.v", "Meant.v")

  /** The library the files are over: the trees, what is computed from them, and their meaning. */
  private val library = List("Threads/Prog", "Threads/Jdk", "Threads/Sem", "Threads/Lang", "Scala/Tree",
    "Scala/Program", "Scala/Table", "Scala/Value", "Scala/Meaning", "Scala/Library", "Scala/Gaps")

  test(("Rocq reads every file, and checks that Ox's trees are closed, what they take from outside, the kernel, " +
      "what it assumes of the JDK, its variables, and where the meaning of the trees stops").tag(Rocq)) {
    val all = files ++ checked.map(n => n -> Files.readString(out.resolve(n)))
    assertEquals(ThreadsRocq.failing(all.map((name, text) => s"Ox/Tree/$name" -> text), library), None)
  }
