package frflow.project.rocq

import clients.{Failures, Joins, Observed, Scopes}

/** Programs written against Ox, each a method of an object that takes nothing and answers a number: the object,
  * the method, and the method itself, to be run on the JVM; and the Rocq file that says what each gives.
  */
object OxClients:
  final case class Program(owner: String, name: String, run: () => Int):
    def lemma: String = s"${owner.split('.').last.stripSuffix("$")}_$name"

  private def of(owner: AnyRef)(named: (String, () => Int)*): List[Program] =
    named.toList.map((name, run) => Program(owner.getClass.getName, name, run))

  private val joins = of(Joins)(
    "plain" -> Joins.plain, "scoped" -> Joins.scoped, "forkJoin" -> Joins.forkJoin, "two" -> Joins.two)

  private val failures = of(Failures)(
    "userForkThrows" -> Failures.userForkThrows,
    "joinedForkThrows" -> Failures.joinedForkThrows,
    "bodyThrows" -> Failures.bodyThrows,
    "daemonInterrupted" -> Failures.daemonInterrupted,
    "unsupervisedThrows" -> Failures.unsupervisedThrows,
    "cancelled" -> Failures.cancelled,
    "applicationError" -> Failures.applicationError)

  private val scopes = of(Scopes)(
    "nested" -> Scopes.nested,
    "parTwo" -> Scopes.parTwo,
    "raceOne" -> Scopes.raceOne,
    "timedOut" -> Scopes.timedOut,
    "finalizers" -> Scopes.finalizers,
    "resource" -> Scopes.resource,
    "forkLocal" -> Scopes.forkLocal)

  private val observed = of(Observed)(
    "waitsForUserForks" -> Observed.waitsForUserForks,
    "interruptsAndWaits" -> Observed.interruptsAndWaits,
    "failureInterruptsSibling" -> Observed.failureInterruptsSibling,
    "innerEndsFirst" -> Observed.innerEndsFirst,
    "finalizerAfterForks" -> Observed.finalizerAfterForks,
    "unsupervisedWaits" -> Observed.unsupervisedWaits,
    "cancelWaits" -> Observed.cancelWaits)

  val all: List[Program] = joins ++ failures ++ scopes ++ observed

  private val said: String =
    """(** Programs written against Ox 1.1.0 (`frflow.project.rocq.clients`), run: the meaning of their trees and of
      |    Ox's (`FrFlow.Scala.Meaning`), executed (`FrFlow.Scala.Run`). Each lemma says that the first thread gives
      |    the number the same method gave on the JVM when this file was generated, and that every thread ended,
      |    with the threads taking turns in each of four orders. Four runs of each are checked: the runs under
      |    other orders, and with the JDK doing another of the things its contracts allow, are not.
      |    Generated by FrFlow (`OxRunSuite`): do not edit. *)""".stripMargin

  private def quoted(s: String): String = "\"" + s + "\""

  private def requires(files: List[String]): String =
    s"""From Stdlib Require Import String List ZArith.
       |Require Import FrFlow.Threads.Prog FrFlow.Threads.Jdk FrFlow.Threads.Sem.
       |Require Import FrFlow.Scala.Tree FrFlow.Scala.Program FrFlow.Scala.Table FrFlow.Scala.Value.
       |Require Import FrFlow.Scala.Meaning FrFlow.Scala.Library FrFlow.Scala.Run.
       |Require Import Ox.Tree.All.
       |${files.map(n => s"Require Ox.Client.$n.").mkString("\n")}
       |Import ListNotations.
       |Open Scope string_scope.""".stripMargin

  /** The trees the programs are run over, and how one is run. */
  private def setting(files: List[String], owners: List[String]): String =
    s"""Definition all : list tree :=
       |  [${files.map(n => s"$n.$n").mkString(";\n   ")}] ++ files.
       |Definition T : table := Eval vm_compute in build all.
       |Definition owners : list string :=
       |  [${owners.map(quoted).mkString(";\n   ")}].
       |
       |(** The objects with state the programs may use: made before a program starts. *)
       |Definition modules : list string := Eval vm_compute in needed T all (declared_by all owners).
       |
       |(** The orders the threads take turns in: each in turn, and three that follow no pattern. *)
       |Definition orders : list (nat -> nat) := (fun turn => turn) :: map shuffled [1; 2; 3].
       |
       |(** Under each order every thread ends, and the first gives the number `n`. *)
       |Definition gives (owner name : string) (n : Z) : bool :=
       |  forallb (fun order =>
       |    match result (execute_under T outside supers order 100000 modules (Member owner name ":scala.Int")) with
       |    | Some (inr (VObj (Int m))) => Z.eqb m n
       |    | _ => false
       |    end) orders.""".stripMargin

  /** `Runs.v`: over the trees `files` name, a lemma for each program and what it gave. */
  def runs(files: List[String], gave: List[(Program, Int)]): String =
    List(said, requires(files), setting(files, gave.map(_._1.owner).distinct), gave.map(lemma).mkString("\n\n"))
      .mkString("", "\n\n", "\n")

  private def lemma(p: Program, gave: Int): String =
    s"""Lemma ${p.lemma} : gives ${quoted(p.owner)} ${quoted(p.name)} ($gave)%Z = true.
       |Proof. vm_compute. reflexivity. Qed.""".stripMargin
