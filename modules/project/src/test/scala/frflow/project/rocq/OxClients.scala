package frflow.project.rocq

import clients.{Failures, Joins, Observed, Scopes}
import frflow.core.code.ClassFacts

/** Programs written against Ox, each a method of an object that takes nothing and answers a number: the object,
  * the method, and the method itself, to be run on the JVM; and the Rocq file that says what each gives.
  */
object OxClients:
  final case class Program(owner: String, name: String, run: () => Int):
    def lemma: String = s"${owner.split('.').last.stripSuffix("$")}_$name"

  private def of(owner: AnyRef)(named: (String, () => Int)*): List[Program] =
    named.toList.map((name, run) => Program(owner.getClass.getName, name, run))

  private val joins = of(Joins)(
    "plain" -> Joins.plain, "scoped" -> Joins.scoped, "forkJoin" -> Joins.forkJoin, "two" -> Joins.two)

  private val failures = of(Failures)(
    "userForkThrows" -> Failures.userForkThrows,
    "joinedForkThrows" -> Failures.joinedForkThrows,
    "bodyThrows" -> Failures.bodyThrows,
    "daemonInterrupted" -> Failures.daemonInterrupted,
    "unsupervisedThrows" -> Failures.unsupervisedThrows,
    "cancelled" -> Failures.cancelled,
    "applicationError" -> Failures.applicationError)

  private val scopes = of(Scopes)(
    "nested" -> Scopes.nested,
    "parTwo" -> Scopes.parTwo,
    "raceOne" -> Scopes.raceOne,
    "timedOut" -> Scopes.timedOut,
    "finalizers" -> Scopes.finalizers,
    "resource" -> Scopes.resource,
    "forkLocal" -> Scopes.forkLocal)

  private val observed = of(Observed)(
    "waitsForUserForks" -> Observed.waitsForUserForks,
    "interruptsAndWaits" -> Observed.interruptsAndWaits,
    "failureInterruptsSibling" -> Observed.failureInterruptsSibling,
    "innerEndsFirst" -> Observed.innerEndsFirst,
    "finalizerAfterForks" -> Observed.finalizerAfterForks,
    "unsupervisedWaits" -> Observed.unsupervisedWaits,
    "cancelWaits" -> Observed.cancelWaits)

  val all: List[Program] = joins ++ failures ++ scopes ++ observed

  private val said: String =
    """(** Programs written against Ox 1.1.0 (`frflow.project.rocq.clients`), run: the meaning of their trees and of
      |    Ox's (`FrFlow.Scala.Meaning`), executed by the machine that keeps calls apart and writes its run out as
      |    an execution (`FrFlow.Code.Frames`). The programs run are those an execution of the code is of
      |    (`FrFlow.Code.Outside`): a call of the JDK is one operation named by the definition called, and the
      |    machine runs for it what the library says of that definition (`Library.of_label`).
      |    A lemma for each program (`Runs1.v` to `Runs4.v`, which Rocq can check at once) says that the first
      |    thread gives the number the same method gave on the JVM when the files were generated, and that every
      |    thread ended, with the threads taking turns in each of four orders. Four runs of each are checked: the
      |    runs under other orders, and with the JDK doing another of the things its contracts allow, are not.
      |    The machine takes a step only where an execution of the code has one (`FrFlow.Code.Checks`), and stops
      |    otherwise: so each run that ends here took only such steps, and what it did is an execution of the
      |    code (`executions`, by `FrFlow.Code.Executed`).
      |    Generated by FrFlow (`OxRunSuite`): do not edit. *)""".stripMargin

  private def quoted(s: String): String = "\"" + s + "\""

  private def requires(files: List[String]): String =
    s"""From Stdlib Require Import String List ZArith.
       |Require Import FrFlow.Threads.Prog FrFlow.Jvm.Machine.
       |Require Import FrFlow.Scala.Tree FrFlow.Scala.Program FrFlow.Scala.Table FrFlow.Scala.Value.
       |Require Import FrFlow.Scala.Meaning FrFlow.Scala.Library FrFlow.Scala.Run.
       |Require Import FrFlow.Code.Conforms FrFlow.Code.Frames.
       |Require FrFlow.Code.Witness FrFlow.Code.Executed.
       |Require Import Ox.Tree.All.
       |${files.map(n => s"Require Ox.Client.$n.").mkString("\n")}
       |Import ListNotations.
       |Open Scope string_scope.""".stripMargin

  private def texts(names: List[String]): String = names.map(quoted).mkString("[", "; ", "]")

  /** The trees the programs are run over. */
  private def setting(files: List[String]): String =
    s"""(** Ox's definitions, then the programs': what Ox's names mean does not depend on the programs. *)
       |Definition programs : list tree :=
       |  [${files.map(n => s"$n.$n").mkString(";\n   ")}].
       |Definition Ox : table := Eval vm_compute in build files.
       |Definition T : table := Eval vm_compute in extend Ox (build_after Ox programs).""".stripMargin

  /** What is known of the classes they mention. */
  private def classes(known: ClassFacts): String =
    s"""(** What is known of the classes Ox and the programs mention, from their class files. *)
       |Definition known : classes :=
       |  Classes ${texts(known.identities)}
       |    ${texts(known.throwables)}
       |    ${texts(known.functions)}
       |    ${texts(known.heirs)}
       |    ${texts(known.objects)}.""".stripMargin

  /** How a program is run, and that what a run does is an execution of the code. */
  private val running: String =
    """(** The orders the threads take turns in: each in turn, and three that follow no pattern. *)
      |Definition orders : list (nat -> nat) := (fun turn => turn) :: map shuffled [1; 2; 3].
      |
      |(** Under each order every thread ends, and the first gives the number `n`. *)
      |Definition gives (owner name : string) (n : Z) : bool :=
      |  forallb (fun order =>
      |    match result (fst (fst (execute_frames T known of_label order 100000
      |        (Member owner name ":scala.Int")))) with
      |    | Some (inr (VObj (Int m))) => Z.eqb m n
      |    | _ => false
      |    end) orders.
      |
      |(** What a run does, under any order and for any length, is an execution of the code. *)
      |Lemma executions (order : nat -> nat) (fuel : nat) (main : sym) v es refs :
      |  execute_frames T known of_label order fuel main = (v, es, refs) ->
      |  runs (files ++ programs) T known (Witness.history_of es).
      |Proof. apply Executed.machine_conforms. vm_compute. reflexivity. Qed.""".stripMargin

  /** The files the lemmas are in: as many as are checked at once. */
  val parts: Int = 4

  /** Whether the file is one of the lemmas, to be checked at once with the others. */
  def together(file: String): Boolean = (1 to parts).exists(i => file == s"Runs$i.v")

  /** `Runs.v`: over the trees `files` name, how a program is run. Then `Runs1.v` to `Runs4.v`: a lemma for each
    * program and what it gave, dealt out in turn.
    */
  def runs(files: List[String], known: ClassFacts, gave: List[(Program, Int)]): List[(String, String)] =
    val how = List(said, requires(files), setting(files), classes(known), running).mkString("", "\n\n", "\n")
    val dealt = gave.zipWithIndex.groupMap((_, i) => i % parts)((g, _) => g)
    ("Runs.v" -> how) :: (0 until parts).toList.map(i => s"Runs${i + 1}.v" -> part(dealt.getOrElse(i, Nil)))

  /** One file of lemmas, over `Runs.v`. */
  private def part(gave: List[(Program, Int)]): String =
    val head = """(** What some of the programs give, run as `Runs.v` says: the number the same method gave on the JVM.
                 |    Generated by FrFlow (`OxRunSuite`): do not edit. *)
                 |
                 |From Stdlib Require Import String List ZArith.
                 |Require Import Ox.Client.Runs.
                 |Open Scope string_scope.""".stripMargin
    (head :: gave.map(lemma)).mkString("", "\n\n", "\n")

  private def lemma(p: Program, gave: Int): String =
    s"""Lemma ${p.lemma} : gives ${quoted(p.owner)} ${quoted(p.name)} ($gave)%Z = true.
       |Proof. vm_compute. reflexivity. Qed.""".stripMargin
