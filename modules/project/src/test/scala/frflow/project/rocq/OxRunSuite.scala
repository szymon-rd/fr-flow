package frflow.project.rocq

import frflow.core.code.{ClassFacts, Datum}
import frflow.core.staged.Stage
import frflow.dsl.compiled.source.{ReadClasses, ReadSource}
import frflow.proof.rocq.{PrintData, StagedModule}
import java.nio.file.{Files, Path}
import scala.jdk.CollectionConverters.*

/** Programs written against Ox (`clients`), read into trees as Ox itself is, and the meaning of the trees run in
  * Rocq as the programs an execution of the code is of (`FrFlow/Code/Outside.v`), by the machine that writes its
  * run out as an execution (`FrFlow/Bridge/Frames.v`): each must give there what the same method gives on the JVM.
  * What Rocq runs is the code staged into programs (`frflow.core.staged.Stage`), Ox's and the programs': it is
  * how the staging, and the meaning given to Scala's trees and to the JDK, are tested. `FRFLOW_ROCQ_WRITE=1`
  * writes the files anew.
  */
class OxRunSuite extends munit.FunSuite:
  override val munitTimeout = scala.concurrent.duration.Duration(60, "min")

  private val out = Path.of("examples/ox/rocq/Ox/Client")
  private val trees = Path.of(sys.env.getOrElse("FRFLOW_OX_TREES", "examples/ox/rocq/Ox/Tree"))
  private lazy val read: List[(String, Datum)] = ReadSource.only(classOf[clients.Joins.type], _.contains("/clients/"))
  private def within(path: String): String = path.split("/test-classes/").last
  private def named(path: String): String =
    "client_" + path.split('/').last.stripSuffix(".tasty").replaceAll("[^A-Za-z0-9]", "_")

  private lazy val programs: List[(String, String)] = read.map((path, d) =>
    s"${named(path)}.v" -> PrintData.file(named(path), s"${within(path)} of FrFlow's tests, as the tree it " +
      "holds. Generated by FrFlow (`frflow.dsl.compiled.source`): do not edit.", d))

  /** Ox's trees, then the programs'. */
  private lazy val code: List[Datum] = (ReadSource(classOf[_root_.ox.Ox]) ++ read).map(_._2)

  /** What is known of the classes Ox's trees and the programs' mention, from their class files. */
  private lazy val known: ClassFacts =
    code.map(ReadClasses.of(_, getClass.getClassLoader)).foldLeft(ClassFacts.none)(_ ++ _)

  /** Ox's code and the programs', staged: computed from the trees, and not kept. */
  private lazy val staged: (String, String) = "Programs.v" -> StagedModule(Stage(code))

  /** The programs' trees, and the files that say what each program gave on the JVM, now. */
  private lazy val files: List[(String, String)] =
    programs ++ OxClients.runs(programs.map(_._1.stripSuffix(".v")), known, OxClients.all.map(p => p -> p.run()))

  test("the generator prints the files that are kept: the programs' trees, and what each gives on the JVM") {
    if sys.env.contains("FRFLOW_ROCQ_WRITE") then
      Files.createDirectories(out)
      files.foreach((name, text) => Files.writeString(out.resolve(name), text))
    files.foreach((name, text) => assertEquals(text, Files.readString(out.resolve(name)), name))
    assertEquals(OxClients.all.size, 25)
  }

  /** Ox's trees as they are kept (`OxSourceSuite` checks them against Ox's TASTy), then their index. */
  private def ox: List[(String, String)] =
    val listed = Files.list(trees)
    val names = try listed.iterator.asScala.map(_.getFileName.toString).toList finally listed.close()
    (names.filter(n => n.startsWith("ox_") && n.endsWith(".v")).sorted :+ "All.v").map(n =>
      s"Ox/Tree/$n" -> Files.readString(trees.resolve(n)))

  private val library = List("Base", "Executions", "Jvm/Prog", "Jvm/Machine", "Jvm/Races", "Scala/Tree",
    "Scala/Program", "Scala/Table", "Scala/Equal", "Scala/Value", "Scala/Meaning", "Scala/Jdk", "Scala/Library",
    "Scala/Run", "Code/Outside", "Code/Conforms", "Code/Classes", "Rules/Walk", "Code/Witness", "Code/Staged",
    "Bridge/Names",
    "Bridge/Checks", "Bridge/Frames", "Bridge/Steps", "Bridge/Kept", "Bridge/Stages", "Bridge/Heap", "Bridge/Bridge",
    "Bridge/Executed")

  test("Rocq runs the meaning of each program over Ox's trees, and it gives what the JVM gave".tag(Rocq)) {
    val (lemmas, before) = files.partition((name, _) => OxClients.together(name))
    def placed(of: List[(String, String)]) = of.map((name, text) => s"Ox/Client/$name" -> text)
    assertEquals(ThreadsRocq.failingTogether(ox ++ placed(staged :: before), library, placed(lemmas)), None)
  }
