package frflow.project.rocq

import frflow.core.threads.Datum

/** The files written beside Ox's trees: their index (`All.v`), and what the trees take from outside Ox
  * (`Surface.v`), which Rocq checks against what it computes from the trees itself.
  */
object OxSource:
  /** `name` is `pkg`, or inside it. */
  def within(pkg: String, name: String): Boolean = name == pkg || name.startsWith(s"$pkg.")

  /** The members a tree reads, selects or calls, each as its owner, name and signature; a package is none, and
    * an import is no code.
    */
  def mentioned(d: Datum): List[List[String]] = d match
    case Datum.Of("Imported" | "Exported", _) => Nil
    case Datum.Of("Ident" | "Select", args) => args.flatMap(member) ++ args.flatMap(mentioned)
    case Datum.Of(_, args)                  => args.flatMap(mentioned)
    case Datum.Many(elems)                  => elems.flatMap(mentioned)
    case Datum.Maybe(value)                 => value.toList.flatMap(mentioned)
    case _                                  => Nil

  private def member(d: Datum): Option[List[String]] = d match
    case Datum.Of("Member", List(Datum.Text(o), Datum.Text(n), Datum.Text(s))) if s != "package" => Some(List(o, n, s))
    case _                                                                                      => None

  private def head(more: String): String =
    s"""From Stdlib Require Import String List.
       |Require Import FrFlow.Scala.Tree FrFlow.Scala.Program$more.""".stripMargin

  /** `All.v`: every file's tree, in one list. */
  def index(names: List[String]): String =
    s"""(** Ox 1.1.0, whole: the tree of every TASTy file of ${OxUnit.jar}. Generated by FrFlow: do not edit. *)
       |
       |${head("")}
       |${names.map(n => s"Require Ox.Tree.$n.").mkString("\n")}
       |Import ListNotations.
       |
       |Definition files : list tree :=
       |  [${names.map(n => s"$n.$n").mkString(";\n   ")}].
       |""".stripMargin

  private val said: String =
    """(** What Ox 1.1.0 takes from outside itself: every definition of the JDK, of Scala's library and of jox that
      |    its code reads or calls, by its owner, its name and its signature. A proof about Ox's code rests on what
      |    these do: each is to be given a contract, or shown not to matter. `closed` says the trees are the whole
      |    of Ox: nothing of Ox is referred to and not defined in them. `surface_is` says the list is exact.
      |    Generated by FrFlow: do not edit. *)""".stripMargin

  private def quoted(s: String): String = "\"" + s.replace("\"", "\"\"") + "\""

  /** `Surface.v`: what Ox takes from outside, listed, and that the list is what Rocq computes from the trees. */
  def surface(members: List[List[String]]): String =
    s"""$said
       |
       |${head(" Ox.Tree.All")}
       |Import ListNotations.
       |Open Scope string_scope.
       |
       |Definition surface : list sym :=
       |  [${members.map(m => s"Member ${m.map(quoted).mkString(" ")}").mkString(";\n   ")}].
       |
       |Lemma closed : undefined "ox" files = [].
       |Proof. vm_compute. reflexivity. Qed.
       |
       |Lemma surface_is : same (outside "ox" files) surface = true.
       |Proof. vm_compute. reflexivity. Qed.
       |""".stripMargin
