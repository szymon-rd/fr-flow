Definition Scenarios_computing (this : ref) : prog Z :=
  n <- new C_Numbers ;;
  call n M_Numbers_new tt ;;;
  either <- call n M_Numbers_either (true, false) ;;
  chosen <- (if either then
        either1 <- call n M_Numbers_either (true, true) ;;
        ret (negb either1)
      else
        ret false) ;;
  let truths := if chosen then 1 else 0 in
  largest <- call n M_Numbers_largest (3, 9, 4) ;;
  gcd <- call n M_Numbers_gcd (84, 36) ;;
  triangle <- call n M_Numbers_triangle 6 ;;
  signOf <- call n M_Numbers_signOf (-5) ;;
  ret (iadd (iadd (iadd (iadd largest (imul gcd 10)) (imul triangle 1000)) signOf) (imul truths 100000)).

Definition Scenarios_wrapping (this : ref) : prog Z :=
  n <- new C_Numbers ;;
  call n M_Numbers_new tt ;;;
  power <- call n M_Numbers_power (7, 20) ;;
  power1 <- call n M_Numbers_power (-3, 31) ;;
  ret (iadd power power1).

Definition Scenarios_edges (this : ref) : prog Z :=
  e <- new C_Edges ;;
  call e M_Edges_new tt ;;;
  first <- get e F_Edges_first ;;
  receiver <- call e M_Edges_receiver tt ;;
  looping <- call e M_Edges_looping tt ;;
  cells <- call e M_Edges_cells tt ;;
  ret (iadd (iadd (iadd first (imul receiver 10)) (imul looping 1000)) (imul cells 100000)).

Definition Scenarios_naming (this : ref) : prog Z :=
  Edges <- new C_Edges ;;
  call Edges M_Edges_new tt ;;;
  overloads <- call Edges M_Edges_overloads tt ;;
  ret overloads.

Definition Scenarios_ordering (this : ref) : prog Z :=
  Edges <- new C_Edges ;;
  call Edges M_Edges_new tt ;;;
  ordering <- call Edges M_Edges_ordering tt ;;
  ret ordering.

