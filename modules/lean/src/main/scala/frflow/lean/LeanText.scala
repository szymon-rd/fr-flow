package frflow
package lean

import frflow.protocol.ObligationName

/** The open terms a Lean declaration takes, by name, in order: opaque types first, then parameters. */
final case class Ctx(opaques: List[String], params: List[String]):
  def ++(o: Ctx): Ctx = Ctx((opaques ++ o.opaques).distinct, (params ++ o.params).distinct)
  def names: List[String] = opaques ++ params
  def isEmpty: Boolean = names.isEmpty

object Ctx:
  val empty: Ctx = Ctx(Nil, Nil)
  def all(cs: Iterable[Ctx]): Ctx = cs.foldLeft(empty)(_ ++ _)

/** What some terms stand for instead of themselves (code, doing nothing, a value), with the terms it mentions. */
type Env = Map[String, (String, Ctx)]

final case class LeanModule(name: String):
  def path: String = name.replace('.', '/') + ".lean"

/** Where the Lean of a knowledge base lives (docs/DAG.md §3): generated in `FrFlowGen/<KB>/`, authored in
  * `Proofs/<KB>/` (per node, and the shared `Lemmas`).
  */
final case class Layout(kb: String):
  private def generated(rest: String) = LeanModule(s"FrFlowGen.$kb.$rest")
  // A name Lean reads as a keyword is escaped (`«matches»`); a module's name is prefixed, so plain.
  private def plain(name: String) = name.filterNot("«»".contains(_))
  val types: LeanModule = generated("Types")
  val domain: LeanModule = generated("Domain")
  val rootImpl: LeanModule = generated("RootImpl")
  val boundaries: LeanModule = generated("Boundaries")
  val lemmas: LeanModule = LeanModule(s"Proofs.$kb.Lemmas")
  def definition(name: String): LeanModule = generated(s"Domain.Def_${plain(name)}")
  def term(name: String): LeanModule = generated(s"Domain.Term_${plain(name)}")
  def spec(id: String): LeanModule = generated(s"$id.Spec")
  def auto(id: String): LeanModule = generated(s"$id.Auto")
  def theorems(id: String): LeanModule = generated(s"$id.Theorems")
  def impl(id: String): LeanModule = generated(s"$id.Impl")
  def checks(id: String): LeanModule = generated(s"$id.Checks")
  def eval(id: String): LeanModule = generated(s"$id.Eval")
  def proofs(id: String): LeanModule = LeanModule(s"Proofs.$kb.$id")
  def generatedDirs: List[String] = List(s"FrFlowGen/$kb", s"FrFlowAudit/$kb")

/** The pieces generated Lean is written with. */
object LeanText:
  val Header = "-- GENERATED by FrFlow from the Scala model. Do not edit.\n\n"
  val Preamble = "set_option autoImplicit false\nset_option linter.unusedVariables false\nnoncomputable section\nopen Classical\n\n"
  /** Each module generates its own matches' equations: generated twice, Lean's `_sparseCasesOn` clashes on import. */
  val MatchEqns = "frflow_match_eqns\n"
  /** The theorem of each node: it holds of every world that meets the leaves below it. */
  val Holds = "holds"
  def imports(ms: List[LeanModule]): String = ms.map(m => s"import ${m.name}\n").mkString
  def module(uses: List[LeanModule], ns: String, body: String, opens: Option[String] = None): String =
    Header + imports(uses) + "\n" + Preamble + s"namespace $ns\n" + opens.fold("")(o => s"open $o\n") + "\n" + body + s"end $ns\n"
  // A `-/` in the text would end the comment early.
  def doc(text: String): String = s"/-- ${text.replace("-/", "- /")} -/\n"
  def definition(name: String, binders: String, tpe: String, body: String): String =
    s"@[frflow_defs] def $name${if binders.isEmpty then "" else " " + binders} : $tpe :=\n  $body"

  def forall(binders: String, hyps: List[(String, String)], conclusion: String): String =
    (if binders.isEmpty then "" else s"∀ $binders, ") +
      (if hyps.isEmpty then "" else s"∀ ${hyps.map((h, t) => s"($h : $t)").mkString(" ")}, ") + conclusion

  /** The binders and the arguments of a call `op x0 x1` of an operation taking `types`. */
  def call(types: List[String]): (String, String) =
    (types.zipWithIndex.map((t, i) => s"(x$i : $t)").mkString(" "), types.indices.map(i => s"x$i").mkString(" "))
  def byAuto(o: ObligationName): String = s"by\n  unfold Obl.$o\n  frflow_auto"

  /** The top-level conjuncts of a proposition as the translator writes it (each `&&` in parentheses), in order; itself
    * when it is not a conjunction. It is cut only where nothing but `∧` stands between groups and applications, which is
    * where Lean cuts it: a binder, an arrow, `∨` or `¬` there keeps the text whole.
    */
  def conjuncts(prop: String): List[String] =
    val t = prop.trim
    val inner = if enclosed(t) then t.substring(1, t.length - 1).trim else t
    atAnds(inner) match
      case ps @ (_ :: _ :: _) if ps.forall(_.nonEmpty) => ps.flatMap(conjuncts)
      case _ => List(t)

  private val Keywords = Set("fun", "if", "then", "else", "let", "match", "with", "do", "have", "show", "by", "in", "at", "from")
  /** The depth after each character (brackets of every kind; a string's text is at depth -1, never cut). */
  private def levels(t: String): IndexedSeq[Int] =
    var (depth, inString) = (0, false)
    t.indices.map { i =>
      val c = t(i)
      if inString then { if c == '"' && t(i - 1) != '\\' then inString = false; -1 }
      else if c == '"' then { inString = true; -1 }
      else
        if "([{⟨".contains(c) then depth += 1 else if ")]}⟩".contains(c) then depth -= 1
        depth
    }
  private def enclosed(t: String): Boolean = t.startsWith("(") && levels(t).indexWhere(_ == 0) == t.length - 1
  private def atAnds(t: String): List[String] =
    val ls = levels(t)
    val top = t.indices.map(i => if ls(i) == 0 && !")]}⟩".contains(t(i)) then t(i) else ' ').mkString
    val plain = top.forall(c => c.isLetterOrDigit || c.isWhitespace || "_.'«»∧".contains(c)) && ls.forall(_ >= -1) &&
      !top.split("[^\\p{L}\\p{N}_'.«»]+").exists(Keywords)
    val cuts = t.indices.filter(top(_) == '∧').toList
    if !plain || cuts.isEmpty then List(t)
    else (-1 :: cuts).zip(cuts :+ t.length).map((from, to) => t.substring(from + 1, to).trim)

/** A Lean type, read back from its text. */
enum LeanType:
  case Name(n: String)
  case ListOf(t: LeanType)
  case OptionOf(t: LeanType)
  case Prod(a: LeanType, b: LeanType)
  case Fun(text: String)

object LeanType:
  private def depths(t: String): IndexedSeq[Int] = t.scanLeft(0)((d, c) => if c == '(' then d + 1 else if c == ')' then d - 1 else d).tail
  private def atTop(t: String, sym: String): Option[Int] = { val d = depths(t); t.indices.find(i => d(i) == 0 && t.startsWith(sym, i)) }
  private def wrapped(t: String): Boolean = t.startsWith("(") && depths(t).indexWhere(_ == 0) == t.length - 1

  def parse(t0: String): LeanType =
    val t = t0.trim
    if wrapped(t) then parse(t.substring(1, t.length - 1))
    else if atTop(t, "→").isDefined then Fun(t)
    else atTop(t, "×") match
      case Some(i)                         => Prod(parse(t.take(i)), parse(t.drop(i + 1)))
      case None if t.startsWith("List ")   => ListOf(parse(t.drop(5)))
      case None if t.startsWith("Option ") => OptionOf(parse(t.drop(7)))
      case None                            => Name(t)

  /** `A → (B → C) → D` is `A`, `(B → C)`, `D`. */
  def arrows(t0: String): List[String] =
    val x = t0.trim
    val t = if x.startsWith("(") && x.endsWith(")") && (0 +: depths(x.init.tail)).forall(_ >= 0) then x.init.tail.trim else x
    val d = depths(t)
    val cuts = t.indices.filter(i => d(i) == 0 && t.startsWith(" → ", i)).toList
    (0 :: cuts.map(_ + 3)).zip(cuts :+ t.length).map((from, to) => t.substring(from, to).trim)

  /** Doing nothing, for an operation of type `t`: `[]`, `none`, `False`, or an input unchanged. */
  def nothing(t: String): Option[String] =
    val ps = arrows(t)
    val (ins, r) = (ps.init, ps.last)
    val v = if ins.isEmpty then None
      else if r == "Prop" then Some("False")
      else if r.startsWith("(List ") || r.startsWith("List ") then Some("[]")
      else if r.startsWith("(Option ") || r.startsWith("Option ") then Some("none")
      else ins.indexOf(r) match { case -1 => None; case i => Some(s"x$i") }
    v.map(b => s"(fun ${ins.indices.map(i => s"(x$i : ${ins(i)})").mkString(" ")} => $b)")
