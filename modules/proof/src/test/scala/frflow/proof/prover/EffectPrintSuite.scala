package frflow.proof.prover

import frflow.core.effect.{ClassName, EType, Effect, FieldName, FieldOf, MethodName, MethodOf, OutsideName,
  OutsideOf, Prim, Program, Pure, Tree}
import frflow.proof.effect.PrintProgram

/** A program of effect trees as the Rocq file it is printed to (`docs/EFFECT-TREES.md`). */
class EffectPrintSuite extends munit.FunSuite:
  private val counter = ClassName("Counter")
  private val count = FieldName(counter, "count")
  private val add = MethodName(counter, "add")
  private val log = OutsideName("Log", "say")
  private val (self, n, i) = (Pure.Local("this"), Pure.Local("n"), Pure.Local("i"))

  /** `var i = 0; while i < n do { count = count + 1; i = i + 1 }; Log.say(count); count` */
  private val adding: Tree =
    val turn = Tree.Branch(Pure.Applied(Prim.Less, List(i, n)),
      Tree.Do(Some("count"), Effect.Get(self, count),
        Tree.Do(None, Effect.Put(self, count, Pure.Applied(Prim.Add, List(Pure.Local("count"), Pure.Whole(1)))),
          Tree.Name("i1", Pure.Applied(Prim.Add, List(i, Pure.Whole(1))), Tree.Again(List(Pure.Local("i1")))))),
      Tree.Leave(List(i)))
    Tree.Loop(List("i"), List(Pure.Whole(0)), turn, Tree.Do(Some("count"), Effect.Get(self, count),
      Tree.Do(None, Effect.Ext(log, List(Pure.Local("count"))), Tree.Give(Pure.Local("count")))))

  private val program = Program(List("a.Counter"), List(counter), List(FieldOf(count, EType.Int)),
    List(MethodOf(add, List("this" -> EType.Ref, "n" -> EType.Int), EType.Int, adding)),
    List(OutsideOf(log, List(EType.Int), EType.Unit, "a.Log.say")))

  private val printed = PrintProgram(program)

  private def has(part: String): Unit = assert(printed.contains(part), s"not in the file:\n$part\n\n$printed")

  test("each name is a constructor of its kind's type: a class, a field, a method, what is called outside") {
    has("Inductive class : Type :=\n  | C_Counter.")
    has("Inductive field : Type :=\n  | F_Counter_count.")
    has("Inductive method : Type :=\n  | M_Counter_add.")
    has("Inductive outside : Type :=\n  | O_Log_say.")
  }

  test("an effect's type is read off its name: what a field holds, what a method and an outside call take and give") {
    has("Definition field_ty (f : field) : Type :=\n  match f with\n  | F_Counter_count => Z\n  end.")
    has("Definition method_in (m : method) : Type :=\n  match m with\n  | M_Counter_add => Z\n  end.")
    has("Definition field_of (f : field) : class :=\n  match f with\n  | F_Counter_count => C_Counter\n  end.")
    has("Definition method_of (m : method) : class :=\n  match m with\n  | M_Counter_add => C_Counter\n  end.")
    has("Definition method_out (m : method) : Type :=\n  match m with\n  | M_Counter_add => Z\n  end.")
    has("Definition outside_in (m : outside) : Type :=\n  match m with\n  | O_Log_say => Z\n  end.")
    has("Definition outside_out (m : outside) : Type :=\n  match m with\n  | O_Log_say => unit\n  end.")
  }

  test("a method is its tree: one effect a line, a loop over its state, what is pure a term") {
    has("""Definition Counter_add (this : ref) (n : Z) : prog Z :=
          |  i <- loop (fun i =>
          |      if i <? n then
          |        count <- get this F_Counter_count ;;
          |        put this F_Counter_count (iadd count 1) ;;;
          |        let i1 := iadd i 1 in
          |        again i1
          |      else
          |        leave i) 0 ;;
          |  count <- get this F_Counter_count ;;
          |  ext O_Log_say count ;;;
          |  ret count.""".stripMargin)
  }

  test("a call runs the tree the table gives for the method's name, on the object and what it is given") {
    has("Definition body (m : method) : ref -> method_in m -> prog (method_out m) :=\n  match m with\n" +
      "  | M_Counter_add => fun this n => Counter_add this n\n  end.")
  }

  test("the file says where it was read from, and no line of it is longer than 120 columns") {
    has("(* GENERATED by FrFlow from the TASTy of:\n     a.Counter\n   Do not edit. *)")
    assertEquals(printed.linesIterator.filter(_.length > 120).toList, Nil)
  }

  test("names that would be written alike are told: two fields, two methods, a method as what the file defines") {
    val ab = ClassName("A_b")
    val a = ClassName("A")
    val twice = program.copy(classes = List(ab, a),
      fields = List(FieldOf(FieldName(ab, "c"), EType.Int), FieldOf(FieldName(a, "b_c"), EType.Int)))
    assertEquals(twice.clashes, List("A_b_c"))
    val ty = MethodOf(MethodName(ClassName("field"), "ty"), List("this" -> EType.Ref), EType.Unit,
      Tree.Give(Pure.Nothing))
    assertEquals(program.copy(methods = List(ty)).clashes, List("field_ty"))
    assertEquals(program.clashes, Nil)
  }
