package frflow.proof.layout

import frflow.core.ty.DataType
import frflow.proof.prover.ast.{ModuleName, Names, Preamble, ProverModule}
import frflow.proof.rocq.RocqProject

/** The types of the vocabulary of executions (`frflow.values`, `frflow.executions`: a value of the code, an
  * invocation, its response, an event). Rocq has them once, in FrFlow's library (`FrFlow/Executions.v`), so that
  * what the library says of an execution of code speaks of the same types as a model's statements do: a model that
  * names one imports the library's module, and its own `Types` leaves them out.
  */
object ExecutionsLibrary:
  val module: ModuleName = ModuleName(Names.path("FrFlow", "Executions"))

  /** Whether a type is the vocabulary's: by where Scala declares it. */
  def has(d: DataType): Boolean = scalaName(d).startsWith("frflow.values.") ||
    scalaName(d).startsWith("frflow.executions.")

  /** The names of the fields of the vocabulary's records: the library declares what reads and replaces each. */
  val fields: Set[String] = Set("method", "arguments", "to", "invocation", "field", "value")

  /** The library's module, as FrFlow prints the types `declared` (the vocabulary's, each after those it names). */
  def source(declared: List[DataType]): String =
    val m = ProverModule(module, List(ModuleName(Names.path("FrFlow"))), Preamble.generated, Names.path("FrFlow"),
      Nil, VocabularyModules.inOrder(declared, Nil).map(VocabularyModules.typeDecl))
    RocqProject(List(m)).files.headOption.fold("")(_._2).replace(RocqProject.header, Header)

  val Header: String = "(** The vocabulary of executions: a value of the code, an invocation and its response, an " +
    "event.\n\n    GENERATED by FrFlow from `frflow.values` and `frflow.executions` (`modules/executions`), and " +
    "kept as it is\n    generated (`LibrarySuite`). Do not edit. *)\n\n"

  private def scalaName(d: DataType): String = d match
    case DataType.Product(_, scala, _) => scala
    case DataType.Sum(_, scala, _)     => scala
