package frflow.proof.rocq

import frflow.core.name.RelPath
import frflow.proof.prover.ast.{Decl, ProverModule, ModuleName}
import frflow.proof.rocq.RocqNames.Scope

/** The Rocq of a generated project: each module of the generated AST as a `.v` file. A module's imports are
  * exported, as Lean's are passed on. A module with a form Rocq is not printed from yet is left out, named with
  * the form (`unprinted`), and so is every module that imports one.
  */
final class RocqProject(modules: List[ProverModule]):
  private val names = RocqNames.of(modules.flatMap(m => RocqProject.declared(m.namespace.map(_.text), m.decls)))
  private val decl = RocqDecl(names)

  private val texts: List[(ProverModule, Either[String, String])] = modules.map(m => m -> text(m))

  /** The modules not printed, each with why: the form, or the module it imports that is not printed. */
  val unprinted: Map[String, String] =
    val own = texts.collect { case (m, Left(form)) => m.name.dotted -> form }.toMap
    def missing(known: Map[String, String]): Map[String, String] =
      val more = texts.collect { case (m, Right(_)) if !known.contains(m.name.dotted) =>
        m.imports.map(_.dotted).find(known.contains).map(i => m.name.dotted -> s"imports $i") }.flatten.toMap
      if more.isEmpty then known else missing(known ++ more)
    missing(own)

  /** Each printed module's file, under the directory the project's Rocq is in, with its text, in the order
    * given: a module after those it imports.
    */
  val files: List[(String, String)] =
    val printed = texts.collect { case (m, Right(text)) if !unprinted.contains(m.name.dotted) => m -> text }
    val byName = printed.map((m, text) => m.name.dotted -> (m, text)).toMap
    def after(done: List[String], m: ProverModule): List[String] =
      if done.contains(m.name.dotted) then done
      else m.imports.flatMap(i => byName.get(i.dotted)).map(_._1).foldLeft(done)(after) :+ m.name.dotted
    printed.map(_._1).foldLeft(List.empty[String])(after).map(n => RocqProject.file(byName(n)._1.name) -> byName(n)._2)

  /** A module's text, by its name; none of one not printed. */
  def text(name: ModuleName): Option[String] = byFile.get(RocqProject.file(name))

  private lazy val byFile: Map[String, String] = files.toMap

  private def text(m: ProverModule): Either[String, String] =
    given Scope = Scope(m.namespace.map(_.text), m.opens.map(_.map(_.text)), Set.empty)
    try
      val body = (decl.fields(m.decls) :: m.decls.map(decl(_))).filter(_.nonEmpty).mkString("\n\n")
      Right(RocqProject.header + m.imports.map(RocqProject.imported).mkString + "\n" + body + "\n")
    catch case u: RocqExpr.Unsupported => Left(u.form)

object RocqProject:
  val header: String = "(* GENERATED by FrFlow from the Scala model. Do not edit. *)\n\n"

  /** A module's file, relative to the project's `rocq/`. */
  def file(m: ModuleName): String = m.parts.map(p => RocqNames.identifier(p.text)).mkString("/") + ".v"
  /** The same, relative to the project. */
  def path(m: ModuleName): RelPath = RelPath.fromIdentifiers("rocq", file(m))

  /** The module by the name Rocq loads it by. */
  def logical(m: ModuleName): String = m.parts.map(p => RocqNames.identifier(p.text)).mkString(".")

  private def imported(m: ModuleName): String =
    if m.dotted == "FrFlow" then "From FrFlow Require Export Base.\n" else s"Require Export ${logical(m)}.\n"

  /** Every constant a module declares, by its whole path. */
  private def declared(namespace: List[String], decls: List[Decl]): List[List[String]] = decls.flatMap {
    case Decl.Documented(_, inner)  => declared(namespace, List(inner))
    case Decl.Budgeted(_, inner)    => declared(namespace, List(inner))
    case Decl.Namespace(n, ds)      => declared(namespace ++ n.map(_.text), ds)
    case Decl.Def(_, n, _, _, _)    => List(namespace :+ n.text)
    case Decl.Abbrev(_, n, _)       => List(namespace :+ n.text)
    case t: Decl.Theorem            => List(namespace :+ t.name.text)
    case Decl.Structure(n, _)       => List(namespace :+ n.text)
    case Decl.Inductive(n, _)       => List(namespace :+ n.text)
    case _                          => Nil
  }
