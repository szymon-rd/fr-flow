package frflow.proof.rocq

import frflow.core.ty.DataType
import frflow.proof.layout.ExecutionsLibrary

/** The text of FrFlow's library module of the vocabulary of executions (`FrFlow/Executions.v`), as FrFlow prints
  * the types the Scala declares: what the file kept in the library is (`LibrarySuite`).
  */
object ExecutionsText:
  def of(declared: List[DataType]): String =
    RocqProject(List(ExecutionsLibrary.declaring(declared))).files.headOption.fold("")(_._2)
      .replace(RocqProject.header, Header)

  val Header: String = "(** The vocabulary of executions: a value of the code, an invocation and its response, an " +
    "event.\n\n    GENERATED by FrFlow from `frflow.values` and `frflow.executions` (`modules/executions`), and " +
    "kept as it is\n    generated (`LibrarySuite`). Do not edit. *)\n\n"
