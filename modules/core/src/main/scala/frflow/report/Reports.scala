package frflow.report

import frflow.Project
import frflow.ledger.*
import frflow.model.*

/** Status of a node combining approval and verification freshness. */
final case class NodeStatus(
    node: Node,
    approval: String,
    verification: String,
    proven: Int,
    total: Int
):
  def coherent: Boolean = approval == "approved" && verification == "proven"

object Reports:

  def statuses(project: Project): Seq[NodeStatus] =
    val ledger = Ledger.load(project.ws)
    val hashes = project.hashes
    project.theory.topological.map { n =>
      val e = ledger.entry(n.id)
      val h = hashes(n.id)
      val approval = e.approval match
        case None                                => "unapproved"
        case Some(a) if a.specHash == h.spec     => "approved"
        case Some(_)                             => "changed"
      val total = project.renderer.obligations(n).size
      val (verification, proven) = e.lastCheck match
        case None                                => ("not-checked", 0)
        case Some(c) if c.checkHash != h.check   => ("stale", 0)
        case Some(c) => (c.verification.label, c.obligations.count(_.status == ObligationStatus.Proven))
      NodeStatus(n, approval, verification, proven, total)
    }

  def statusTable(project: Project): String =
    val rows = statuses(project)
    val header = Seq("NODE", "NAME", "APPROVAL", "VERIFICATION", "OBLIGATIONS")
    val body = rows.map { s =>
      val depth = project.theory.ancestors(s.node).size
      Seq("  " * depth + s.node.id, s.node.name, s.approval, s.verification, s"${s.proven}/${s.total}")
    }
    val widths = header.indices.map(i => (header +: body).map(_(i).length).max)
    def fmt(r: Seq[String]) = r.zip(widths).map((c, w) => c.padTo(w, ' ')).mkString("  ").stripTrailing
    val summary =
      if rows.nonEmpty && rows.forall(_.coherent) then "Theory is coherent: every node is approved and proven."
      else
        val pending = rows.filterNot(_.coherent).map(_.node.id)
        s"Not yet coherent: ${pending.mkString(", ")} need approval and/or proofs."
    (fmt(header) +: body.map(fmt)).mkString("\n") + "\n\n" + summary + "\n"

  // ---------------------------------------------------------------------------
  // Theory tree
  // ---------------------------------------------------------------------------

  def tree(theory: TheoryModel, mark: Option[String] = None): String =
    val sb = StringBuilder()
    def go(n: Node, prefix: String, last: Boolean, isRoot: Boolean): Unit =
      val branch = if isRoot then "" else if last then "└── " else "├── "
      val here = if mark.contains(n.id) then "   ← this node" else ""
      val assumes = n.spec.events.flatMap(_.assumes.map(_.assumptionId)).distinct
      val note = if assumes.isEmpty then "" else s"   [assumes ${assumes.mkString(", ")}]"
      sb ++= s"$prefix$branch${n.id}  ${n.name}$note$here\n"
      val kids = theory.children(n.id)
      val childPrefix = if isRoot then prefix else prefix + (if last then "    " else "│   ")
      kids.zipWithIndex.foreach((k, i) => go(k, childPrefix, i == kids.size - 1, isRoot = false))
    theory.roots.foreach(r => go(r, "", last = true, isRoot = true))
    sb.result()

  // ---------------------------------------------------------------------------
  // Slice: the bounded context an agent receives to work on one node
  // ---------------------------------------------------------------------------

  def slice(project: Project, n: Node): String =
    val theory = project.theory
    val r = project.renderer
    val status = statuses(project).map(s => s.node.id -> s).toMap
    val ledger = Ledger.load(project.ws)
    val sb = StringBuilder()

    sb ++= s"# Theory slice: ${theory.name} / ${n.id} ${n.name}\n\n"
    sb ++= "Generated by FrFlow. This slice is the complete context for work on this node. " +
      "Reload it instead of relying on earlier context.\n\n"

    sb ++= "## Position in the theory\n\n```\n" + tree(theory, Some(n.id)) + "```\n\n"

    sb ++= "## Path from the root\n\n"
    theory.pathFromRoot(n).foreach { a =>
      val st = status(a.id)
      val here = if a.id == n.id then " (this node)" else ""
      sb ++= s"### ${a.id} ${a.name}$here\n\n"
      sb ++= s"Status: ${st.approval}, ${st.verification} (${st.proven}/${st.total} obligations).\n\n"
      sb ++= s"**Statement.** ${a.statement}\n\n"
      sb ++= s"**Rationale.** ${a.rationale}\n\n"
      if a.spec.invariants.nonEmpty then
        sb ++= "**Invariants declared here:**\n\n"
        a.spec.invariants.foreach(i => sb ++= s"- `${i.name}`: ${if i.doc.nonEmpty then i.doc else i.expr.text}\n")
        sb ++= "\n"
    }

    val gs = r.guarantees(n)
    if gs.nonEmpty then
      sb ++= s"## Properties guaranteed at ${n.id}\n\n"
      sb ++= "Each holds in every reachable state once the node and its ancestors are proven.\n\n"
      gs.foreach { g =>
        val src = if g.isOwn then "declared here" else s"inherited from ${g.origin}"
        sb ++= s"- `${g.invariant}` ($src): theorem `${theory.name}.${g.theoremName}`\n"
      }
      sb ++= "\n"

    val inScope = theory.pathFromRoot(n).flatMap(_.spec.events).flatMap(_.assumes.map(_.assumptionId)).distinct
    if inScope.nonEmpty then
      sb ++= "## Assumptions in scope\n\n"
      inScope.flatMap(theory.assumption).foreach { a =>
        val users = theory.nodes.flatMap(x => x.spec.events.filter(_.assumes.exists(_.assumptionId == a.id)).map(e => s"${x.id}.${e.name}"))
        sb ++= s"- **${a.id} ${a.name}.** ${a.statement} Justification: ${a.justification} Used by: ${users.mkString(", ")}.\n"
      }
      sb ++= "\n"

    sb ++= "## Vocabulary\n\n"
    theory.vocabulary.foreach {
      case VocabEntry.Opaque(name, doc)   => sb ++= s"- `$name` (opaque type): $doc\n"
      case VocabEntry.Alias(name, t, doc) => sb ++= s"- `$name` := `${t.text}`: $doc\n"
    }
    sb ++= "\n"

    theory.parentOf(n).foreach { p =>
      sb ++= s"## Parent model (${p.id})\n\n```lean\n${r.renderModel(p)}```\n\n"
    }
    sb ++= s"## Model of ${n.id}\n\n```lean\n${r.renderModel(n)}```\n\n"

    val results = ledger.entry(n.id).lastCheck.filter(c => project.hashes.get(n.id).exists(_.check == c.checkHash))
      .map(_.obligations.map(o => o.name -> o).toMap).getOrElse(Map.empty)
    sb ++= s"## Obligations of ${n.id}\n\n"
    sb ++= s"Prove each in `lean/${r.proofsPath(n)}` as `theorem <name> : Obl.<name>`.\n\n"
    r.obligations(n).foreach { o =>
      val st = results.get(o.name).map(x => x.status.label + (if x.detail.nonEmpty then s" (${x.detail})" else "")).getOrElse("not checked")
      sb ++= s"### `${o.name}`: $st\n\n${o.description}\n\n```lean\ndef ${o.name} : Prop :=\n  ${o.statement}\n```\n\n"
    }

    val kids = theory.children(n.id)
    if kids.nonEmpty then
      sb ++= "## Children\n\n"
      kids.foreach(k => sb ++= s"- ${k.id} ${k.name}: ${k.statement}\n")
      sb ++= "\n"

    sb ++= """## Rules for work on this node
             |
             |- Prove obligations only in the node's proof file. Helper lemmas are allowed.
             |- Never edit generated files (`FrFlowGen/`, `FrFlowAudit/`): they are overwritten.
             |- Never weaken a statement. A proof must state exactly `Obl.<name>`.
             |- `axiom`, `admit`, `native_decide`, `implemented_by`, `extern`, `unsafe` and `opaque` are rejected.
             |- If an obligation is false, do not work around it: report it and propose a change to the
             |  theory (statement, model, link or assumption), with rationale. Theory changes need human approval.
             |""".stripMargin
    sb.result()

  // ---------------------------------------------------------------------------
  // Digest: the human-readable theory
  // ---------------------------------------------------------------------------

  def digest(project: Project): String =
    val theory = project.theory
    val status = statuses(project).map(s => s.node.id -> s).toMap
    val sb = StringBuilder()
    sb ++= s"# Theory: ${theory.name}\n\n"
    sb ++= "Generated by FrFlow from the theory definition. Do not edit; change the theory and re-run `digest`.\n\n"
    sb ++= "## Structure\n\n```\n" + tree(theory) + "```\n\n"
    sb ++= "## Status\n\n```\n" + statusTable(project) + "```\n\n"

    sb ++= "## Vocabulary\n\n"
    theory.vocabulary.foreach {
      case VocabEntry.Opaque(name, doc)   => sb ++= s"- **$name**: $doc\n"
      case VocabEntry.Alias(name, t, doc) => sb ++= s"- **$name** (`${t.text}`): $doc\n"
    }
    sb ++= "\n"

    if theory.assumptions.nonEmpty then
      sb ++= "## Assumptions\n\n"
      sb ++= "Guarantees hold for every environment that satisfies these assumptions.\n\n"
      theory.assumptions.foreach(a => sb ++= s"- **${a.id} ${a.name}.** ${a.statement}\n  *Justification:* ${a.justification}\n")
      sb ++= "\n"

    sb ++= "## Nodes\n\n"
    theory.topological.foreach { n =>
      val st = status(n.id)
      sb ++= s"### ${n.id} ${n.name}\n\n"
      n.parent.foreach(p => sb ++= s"Refines **$p**. ")
      sb ++= s"Status: ${st.approval}, ${st.verification}.\n\n"
      sb ++= s"${n.statement}\n\n"
      sb ++= s"*Rationale:* ${n.rationale}\n\n"
      if n.spec.events.nonEmpty then
        sb ++= "| Event | Relation to parent | Assumes | Description |\n|---|---|---|---|\n"
        n.spec.events.foreach { e =>
          val rel = e.target match
            case EventTarget.Unspecified      => ""
            case EventTarget.Refines(ae, _)   => s"refines `$ae`"
            case EventTarget.Skip             => "new (refines skip)"
          sb ++= s"| `${e.name}` | $rel | ${e.assumes.map(_.assumptionId).distinct.mkString(", ")} | ${e.description} |\n"
        }
        sb ++= "\n"
      val gs = project.renderer.guarantees(n)
      if gs.nonEmpty then
        sb ++= "Guarantees: " + gs.map(g => if g.isOwn then s"`${g.invariant}`" else s"`${g.invariant}` (from ${g.origin})").mkString(", ") + ".\n\n"
    }
    sb.result()
