  // Examples, evaluated in Lean
  // ---------------------------------------------------------------------------

  private val typeNames: Set[String] = kb.types.map(_.name).toSet
  /** Lean parameter names, with the Param objects they stand for. */
  private val paramObject: Map[String, Param[?]] =
    (kb.nodes.flatMap(_.lifted) ++ kb.defs.map(_.lifted)).flatMap(l => l.paramRefs.map(_._1).zip(l.paramObjects)).toMap

  /** The Lean name of a domain class, as `Lift` declares it (the owner chain without packages). */
  private def leanName(c: Class[?]): String =
    val pkg = c.getPackageName
    val rest = if pkg.isEmpty then c.getName else c.getName.stripPrefix(pkg + ".")
    rest.replaceAll("[^$]*\\$package\\$", "").split('$').filter(_.nonEmpty).map(Names.ident).mkString(".")

  /** A Scala value as a Lean term of the domain: None for what Lean has no value for (a function, an
    * opaque value, a Map).
    */
  def term(v: Any): Option[String] =
    def all(xs: Iterator[Any]) = { val ts = xs.map(term).toList; Option.when(ts.forall(_.isDefined))(ts.flatten) }
    def int(b: BigInt) = if b < 0 then s"($b)" else b.toString
    def ctor(name: String, args: List[String]) = if args.isEmpty then s"$K.$name" else s"($K.$name ${args.mkString(" ")})"
    v match
      case b: Boolean => Some(if b then "True" else "False")
      case i: Int     => Some(int(BigInt(i)))
      case l: Long    => Some(int(BigInt(l)))
      case b: BigInt  => Some(int(b))
      case s: String  => Some(Names.string(s))
      case ()         => Some("()")
      case None       => Some("none")
      case Some(x)    => term(x).map(t => s"(some $t)")
      case l: List[?] => all(l.iterator).map(_.mkString("[", ", ", "]"))
      case t: Product if t.getClass.getName.startsWith("scala.Tuple") => all(t.productIterator).map(_.mkString("(", ", ", ")"))
      case e: scala.reflect.Enum =>
        val c = if typeNames(leanName(e.getClass)) then e.getClass else e.getClass.getSuperclass
        Option.when(typeNames(leanName(c)))(leanName(c)).flatMap(t => all(e.productIterator).map(ctor(s"$t.${Names.ident(e.productPrefix)}", _)))
      case p: Product if typeNames(leanName(p.getClass)) => all(p.productIterator).map(ctor(s"${leanName(p.getClass)}.mk", _))
      case _ => None

  /** An example, evaluated in Lean: `claim` is what Scala computes of it (the contract's verdict, or the
    * result of the proven implementation), `opposite` its negation. Lean proving the opposite means the
    * translation does not mean what the Scala does.
    */
  final case class Eval(name: String, what: String, claim: String, opposite: String)

  /** The examples of a contract Lean evaluates, and why the others are not evaluated (by `eval_i`). */
  def evals(n: Node[?]): (List[Eval], List[(String, String)]) =
    if !formal(n) || n.kind != NodeKind.Contract then (Nil, Nil)
    else
      val c = nodeCtx(n)
      val post = n.post.get.value.asInstanceOf[(Any, Any, Any) => Boolean]
      val impl = provenImpl(n)
      val out = n.cases.zipWithIndex.map { (e, i) =>
        val label = s"example ${i + 1} (${e.note})"
        def valueOf(p: String): Either[String, String] =
          paramObject.get(p).flatMap(po => e.bindings.find(_.param eq po)) match
            case None => Left(s"it gives no value for $p")
            case Some(b) if b.table.isDefined =>
              // A finite table: a function that looks it up.
              val dom = paramTypes.get(p).map(parseType) match
                case Some(LT.Fun(t)) => t.stripPrefix("(").stripSuffix(")").split("→").headOption.map(_.trim)
                case _               => None
              val cases = b.table.get.toList.map((k, v) => for { tk <- term(k); tv <- term(v) } yield (tk, tv))
              if dom.isEmpty || cases.exists(_.isEmpty) then Left(s"Lean has no value for the table $p")
              else Right(s"(fun (k' : ${dom.get}) => ${cases.flatten.foldRight("none")((kv, rest) => s"if k' = ${kv._1} then some ${kv._2} else $rest")})")
            case Some(b) =>
              scala.util.Try(b.value()).toOption.flatMap(term).toRight(s"Lean has no value for $p (a function, or a type Lean does not have; give a lookup as bindTable)")
        val evaluated: Either[String, List[Eval]] = for
          _ <- Either.cond(c.opaques.isEmpty, (), s"the contract leaves ${c.opaques.mkString(", ")} open")
          ps <- c.params.foldRight(Right(Nil): Either[String, List[(String, String)]])((p, acc) => for { v <- valueOf(p); r <- acc } yield (p, v) :: r)
          vals = ps.toMap
          ran <- scala.util.Try(Bindings.within(e.bindings) {
              (post(e.a, e.b, e.result), impl.map(d => d.fn.asInstanceOf[(Any, Any) => Any](e.a, e.b)))
            }).toEither.left.map(x => s"Scala cannot evaluate it: ${x.getMessage}")
          ta <- term(e.a).toRight("Lean has no value for its input")
          tb <- term(e.b).toRight("Lean has no value for its input")
          tr <- term(e.result).toRight("Lean has no value for its result")
        yield
          val (verdict, got) = ran
          val call = s"$K.${n.id}.post${c.params.map(p => " " + vals(p)).mkString} $ta $tb $tr"
          val onPost = Eval(s"eval_$i", label, if verdict then call else s"¬ $call", if verdict then s"¬ $call" else call)
          val onImpl = for { d <- impl; g <- got; tg <- term(g) } yield
            val f = s"($K.${d.name}${defCtx(d).params.map(p => " " + vals(p)).mkString})"
            Eval(s"evalImpl_$i", s"$label, run by ${d.name}", s"$f $ta $tb = $tg", s"$f $ta $tb ≠ $tg")
          onPost :: onImpl.toList
        evaluated.left.map(why => (s"eval_$i", s"$label: $why"))
      }
      (out.collect { case Right(es) => es }.flatten, out.collect { case Left(w) => w })

  def evalPath(id: String) = oblPath(id, "eval")

  /** Each evaluated example, and its opposite, decided by `simp`. */
  def evalFile(n: Node[?]): Option[String] =
    val es = evals(n)._1
    Option.when(es.nonEmpty) {
      Header + s"import ${specModule(n.id)}\n\n" + Preamble + s"namespace $K.${n.id}.Eval\n\n" + es.map { e =>
        s"/-- ${e.what.replace("-/", "- /")} -/\ntheorem ${e.name} : ${e.claim} := by\n  simp [frflow_defs]\n\n" +
          s"theorem ${e.name}_opposite : ${e.opposite} := by\n  simp [frflow_defs]\n\n"
      }.mkString + s"end $K.${n.id}.Eval\n"
    }

  /** The proof of an obligation in a file of its own: the authored theorem of that name, or frflow_auto. */
  def oblFile(n: Node[?], o: Obligation): String =
    val ns = s"$K.${n.id}.${o.name.capitalize}"
    val mine = isAuthored(n, o.name)
    val proof = if mine then s"$K.${n.id}.Proofs.${o.name}" else s"by\n  unfold Obl.${o.name}\n  frflow_auto"
    Header + s"import ${specModule(n.id)}\n" + (if mine then s"import ${proofsModule(n.id)}\n" else "") + "\n" + Preamble +
      s"namespace $ns\nopen $K.${n.id}\n\ntheorem ${o.name} : Obl.${o.name} := $proof\n\nend $ns\n\n#print axioms $ns.${o.name}\n"

  def oblModule(id: String, name: String) = s"FrFlowGen.$K.$id.${name.capitalize}"

  /** The root theorem of a proven implementation: the root holds of the code itself, composed from
    * the node's `root` and its `impl` proof.
    */
  def rootImplFile(n: Node[?]): Option[String] = provenImpl(n).map { d =>
    val a = args(nodeCtx(n))
    val impl = resolve(s"⟦${d.name}⟧")
    val statement = stated(n, "", None, s"${at(n)("rootSpec")} (${at(n)("toRoot")} $impl)")
    val intro = if a.isEmpty then "" else s"  intro $a\n"
    Header + s"import ${theoremsModule(n.id)}\nimport ${oblModule(n.id, "impl")}\n\n" + Preamble +
      s"namespace $K.${n.id}.RootImpl\nopen $K.${n.id}\n\n/-- The root holds of ${d.name}, the code. -/\n" +
      s"theorem root_impl : $statement := by\n$intro  exact ${if a.isEmpty then "root" else s"root $a"} _ ($K.${n.id}.Impl.impl${if a.isEmpty then "" else s" $a"})\n\n" +
      s"end $K.${n.id}.RootImpl\n\n#print axioms $K.${n.id}.RootImpl.root_impl\n"
  }

  /** What frflow_auto tries for a check that the node says nothing. */
  def attempt(n: Node[?], o: Obligation): String =
    val ns = o.name.capitalize
    Header + s"import ${specModule(n.id)}\n\n" + Preamble + s"namespace $K.${n.id}.$ns\nopen $K.${n.id}\n\n" +
      s"theorem ${o.name} : Obl.${o.name} := by\n  unfold Obl.${o.name}\n  frflow_auto\n\nend $K.${n.id}.$ns\n"

  private def modelType(n: Node[?]): String = n.kind match
    case NodeKind.Design | NodeKind.Invariant => "Unit"
    case NodeKind.Root | NodeKind.Refine => n.spec.get.params.head._2
    case NodeKind.Contract           => n.post.get.params.map(_._2).mkString(" → ")
    case NodeKind.Instantiate        => "_"

  private def q(n: Node[?], decl: String) = s"$K.${n.id}.$decl"


  def spec(n: Node[?]): String =
    val c = nodeCtx(n)
    val b = if binders(c).isEmpty then "" else " " + binders(c)
    val a = args(c)
    def at(f: String) = if a.isEmpty then f else s"$f $a"
    val sb = StringBuilder()
    sb ++= Header + s"import ${n.parent.fold(s"FrFlowGen.$K.Domain")(p => specModule(p.id))}\n\n" + Preamble
    sb ++= s"namespace $K.${n.id}\n\n"
    def d(name: String, tpe: String, body: String) =
      sb ++= s"@[frflow_defs] def $name$b${if tpe.isEmpty then "" else s" : $tpe"} :=\n  $body\n\n"
    val m = modelType(n)
    n.kind match
      case NodeKind.Design | NodeKind.Invariant => ()
      case NodeKind.Root =>
        d("spec", s"$m → Prop", resolve(n.spec.get.lean))
        d("toRoot", "", s"fun (m : $m) => m")
        d("rootSpec", "", at("spec"))
        rootClauses(n).zipWithIndex.foreach((c, i) => d(s"rootClause_$i", s"$m → Prop", s"fun (${n.spec.get.params.head._1} : $m) => ${resolve(c)}"))
      case NodeKind.Refine =>
        val p = n.parent.get
        val pa = args(nodeCtx(p))
        def pat(f: String) = if pa.isEmpty then q(p, f) else s"(${q(p, f)} $pa)"
        d("spec", s"$m → Prop", resolve(n.spec.get.lean))
        d("abs", n.abs.get.leanType, resolve(n.abs.get.lean))
        d("toRoot", "", s"fun (m : $m) => ${pat("toRoot")} (${at("abs")} m)")
        d("rootSpec", "", pat("rootSpec"))
        rootClauses(kb.rootOf(n)).indices.foreach(i => d(s"rootClause_$i", "", pat(s"rootClause_$i")))
      case NodeKind.Contract =>
        val p = n.parent.get
        val pa = args(nodeCtx(p))
        def pat(f: String) = if pa.isEmpty then q(p, f) else s"(${q(p, f)} $pa)"
        val post = n.post.get
        val ins = post.params.init
        d("post", post.leanType, resolve(post.lean))
        formalKeeps(n).foreach { (inv, v) =>
          d(s"rule_${inv.id}", inv.spec.get.leanType, resolve(inv.spec.get.lean))
          d(s"view_${inv.id}", v.leanType, resolve(v.lean))
        }
        val vars = ins.indices.map(i => s"x$i").mkString(" ")
        d("spec", s"($m) → Prop", s"fun (f : $m) => ∀ ${ins.zipWithIndex.map((t, i) => s"(x$i : ${t._2})").mkString(" ")}, ${at("post")} $vars (f $vars)")
        // A contract with a signature of its own maps its implementations to the parent's model.
        n.abs.foreach(a => d("abs", a.leanType, resolve(a.lean)))
        d("toRoot", "", if n.abs.isDefined then s"fun (m : $m) => ${pat("toRoot")} (${at("abs")} m)" else s"fun (m : $m) => ${pat("toRoot")} m")
        d("rootSpec", "", pat("rootSpec"))
        rootClauses(kb.rootOf(n)).indices.foreach(i => d(s"rootClause_$i", "", pat(s"rootClause_$i")))
      case NodeKind.Instantiate =>
        n.substs.filterNot(_.isType).foreach { s =>
          val t = s.term.get
          val sb2 = binders(ctx(t))
          sb ++= s"@[frflow_defs] def s_${s.name}${if sb2.isEmpty then "" else " " + sb2} : ${t.leanType} :=\n  ${resolve(t.lean)}\n\n"
        }
        val th = theta(n)
        val p = n.parent.get
        d("spec", "", s"${q(p, "spec")} $th")
        d("toRoot", "", s"${q(p, "toRoot")} $th")
        d("rootSpec", "", s"${q(p, "rootSpec")} $th")
        rootClauses(kb.rootOf(n)).indices.foreach(i => d(s"rootClause_$i", "", s"${q(p, s"rootClause_$i")} $th"))
    if n.kind == NodeKind.Root || n.kind == NodeKind.Refine || n.kind == NodeKind.Contract then
      n.expected.zipWithIndex.foreach { case ((_, l), i) => d(s"expected_$i", l.leanType, resolve(l.lean)) }
    (obligations(n) ++ saysNothing(n).map(_.obligation) ++ idle(n).map(_._1) ++ clauseChecks(n).map(_._1)).foreach { o =>
      sb ++= s"namespace Obl\n\n/-- ${o.description} -/\n@[frflow_defs] def ${o.name} : Prop :=\n  ${o.statement}\n\nend Obl\n\n"
    }
    sb ++= s"end $K.${n.id}\n"
    sb.result()

  /** Named arguments that instantiate the parent's declarations. */
  def theta(n: Node[?]): String =
    val pc = nodeCtx(n.parent.get)
    val byName = n.substs.map(s => s.name -> s).toMap
    val types = pc.opaques.map(o => s"($o := ${byName.get(o).fold(o)(_.lean)})")
    val params = pc.params.map { p =>
      byName.get(p).flatMap(_.term) match
        case Some(t) => s"($p := ${app(s"s_$p", ctx(t))})"
        case None    => s"($p := $p)"
    }
    (types ++ params).mkString(" ")

  def auto(n: Node[?]): String =
    val body = obligation(n).filterNot(_ => authoredLink(n.id)).fold("") { o =>
      if n.assumed then s"/-- Assumed: the developer decided this link by reading; every root theorem resting on it names it. -/\naxiom ${o.name} : Obl.${o.name}\n\n"
      else s"theorem ${o.name} : Obl.${o.name} := by\n  unfold Obl.${o.name}\n  frflow_auto\n\n"
    }
    Header + s"import ${specModule(n.id)}\n\n" + Preamble + s"namespace $K.${n.id}.Auto\nopen $K.${n.id}\n\n$body" + s"end $K.${n.id}.Auto\n"

  def theorems(n: Node[?]): String =
    val c = nodeCtx(n)
    val b = if binders(c).isEmpty then "" else " " + binders(c)
    val a = args(c)
    def at(f: String) = if a.isEmpty then f else s"($f $a)"
    val sb = StringBuilder()
    sb ++= Header + s"import ${autoModule(n.id)}\n"
    if authoredLink(n.id) then sb ++= s"import ${proofsModule(n.id)}\n"
    n.parent.foreach(p => sb ++= s"import ${theoremsModule(p.id)}\n")
    sb ++= "\n" + Preamble + s"namespace $K.${n.id}\n\n"
    val m = if n.kind == NodeKind.Instantiate then "m" else s"(m : ${modelType(n)})"
    val rootStatement = s"∀ $m, ${at("spec")} m → ${at("rootSpec")} (${at("toRoot")} m)"
    val proofOfRoot = n.kind match
      case NodeKind.Root | NodeKind.Design | NodeKind.Invariant => "fun m h => h"
      case NodeKind.Instantiate => s"${q(n.parent.get, "root")} ${theta(n)}"
      case _ =>
        val p = n.parent.get
        val pa = args(nodeCtx(p))
        def pat(f: String) = if pa.isEmpty then q(p, f) else s"(${q(p, f)} $pa)"
        val target = if n.abs.isDefined then s"(${at("abs")} m)" else "m"
        val ref = s"$K.${n.id}.${if authoredLink(n.id) then "Proofs" else "Auto"}.link"
        sb ++= s"/-- ${obligation(n).get.description} -/\n"
        sb ++= s"theorem link$b : ∀ $m, ${at("spec")} m → ${pat("spec")} $target :=\n  ${if a.isEmpty then ref else s"$ref $a"}\n\n"
        s"fun m h => ${pat("root")} $target (${at("link")} m h)"
    sb ++= s"/-- The root theorem holds for every model of ${n.id}. -/\n"
    sb ++= s"theorem root$b : $rootStatement :=\n  $proofOfRoot\n\nend $K.${n.id}\n"
    sb.result()

  /** The statement of the node's `root` theorem, as Lean source. */
  def rootTheorem(n: Node[?]): String =
    val t = theorems(n)
    val from = t.indexOf("theorem root")
    t.substring(from, t.indexOf(" :=", from))

  def auditedTheorems(n: Node[?]): List[String] = List(q(n, "root"))

  /** The axioms standing for the assumed links on a node's path, by node. */
  def assumptions(n: Node[?]): Map[String, String] =
    kb.path(n).filter(a => a.assumed && formal(a)).map(a => s"$K.${a.id}.Auto.link" -> a.id).toMap

  def audit(n: Node[?]): String =
    Header + s"import ${theoremsModule(n.id)}\n\n" + auditedTheorems(n).map(t => s"#print axioms $t\n").mkString

  /** A stub for each obligation, to prove in its place. */
  def stubs(names: List[String]): String =
    names.map(o => s"theorem $o : Obl.$o := by\n  unfold Obl.$o\n  sorry\n\n").mkString

  /** A proof file with a stub for each of `names` (and for `feasible` with the link, unless a proven
    * implementation below witnesses the node).
    */
  def proofFile(n: Node[?], names: List[String] = List("link")): String =
    val witness = kb.nodes.exists(c => provenImpl(c).isDefined && kb.path(c).exists(_ eq n))
    val all = names ++ Option.when(names.contains("link") && !witness && !names.contains("feasible"))("feasible") ++
      Option.when(names.contains("link") && !names.contains("nontrivial"))("nontrivial")
    s"""import ${specModule(n.id)}
       |
       |/-! Authored proofs of the obligations of ${n.id}. Each states exactly its `Obl`. -/
       |
       |$Preamble
       |namespace $K.${n.id}.Proofs
       |open $K.${n.id}
       |
       |${stubs(all)}end $K.${n.id}.Proofs
       |""".stripMargin

  def lakefile(kernelPath: String): String =
    s"""name = "${K.toLowerCase}"
       |defaultTargets = ["FrFlowGen"]
       |
       |[[require]]
       |name = "frflow"
       |path = "$kernelPath"
       |
       |[[lean_lib]]
       |name = "FrFlowGen"
       |globs = ["FrFlowGen.+"]
       |
       |[[lean_lib]]
       |name = "Proofs"
       |globs = ["Proofs.+"]
       |""".stripMargin
