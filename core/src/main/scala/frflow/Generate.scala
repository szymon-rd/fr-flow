package frflow

/** One proof obligation of a node. `step` obligations quantify over a step `next s e t`. */
final case class Obligation(name: String, statement: String, description: String, step: Boolean)

/** Generates the Lean files of a project. Layout, relative to the Lean workspace:
  *
  *   - `FrFlowGen/<P>/Types.lean`            domain types and theory functions
  *   - `FrFlowGen/<P>/<Node>/Spec.lean`      the node's definitions and obligations
  *   - `FrFlowGen/<P>/<Node>/Auto.lean`      `frflow_auto` on every obligation without an authored proof
  *   - `FrFlowGen/<P>/<Node>/Theorems.lean`  `holds`, `link` and `root`
  *   - `FrFlowAudit/<P>/<Node>.lean`         axioms of the node's theorems
  *
  * Authored proofs live in `Proofs/<P>/<Node>.lean` and are never generated.
  *
  * @param authored obligations with an authored proof, per node
  */
final class Generate(project: Project, authored: Map[String, Set[String]] = Map.empty):
  private val P = project.name

  def specModule(id: String) = s"FrFlowGen.$P.$id.Spec"
  def autoModule(id: String) = s"FrFlowGen.$P.$id.Auto"
  def theoremsModule(id: String) = s"FrFlowGen.$P.$id.Theorems"
  def proofsModule(id: String) = s"Proofs.$P.$id"
  def specPath(id: String) = s"FrFlowGen/$P/$id/Spec.lean"
  def autoPath(id: String) = s"FrFlowGen/$P/$id/Auto.lean"
  def theoremsPath(id: String) = s"FrFlowGen/$P/$id/Theorems.lean"
  def proofsPath(id: String) = s"Proofs/$P/$id.lean"
  def auditPath(id: String) = s"FrFlowAudit/$P/$id.lean"
  def generatedDirs = List(s"FrFlowGen/$P", s"FrFlowAudit/$P")

  def isAuthored(id: String, o: String): Boolean = authored.getOrElse(id, Set.empty)(o)

  private val Header = "-- GENERATED by FrFlow from the Scala model. Do not edit.\n\n"
  private val Preamble = "set_option autoImplicit false\nset_option linter.unusedVariables false\nnoncomputable section\nopen Classical\n\n"

  def files: Map[String, String] =
    val perNode = project.nodes.flatMap { n =>
      List(specPath(n.id) -> spec(n), autoPath(n.id) -> auto(n), theoremsPath(n.id) -> theorems(n), auditPath(n.id) -> audit(n))
    }
    (s"FrFlowGen/$P/Types.lean" -> types :: perNode).toMap

  def types: String =
    val decls = project.types.map(_.lean) ++ project.defs.map(_.lean)
    s"$Header${"import FrFlow"}\n\n$Preamble" + s"namespace $P\n\n${decls.mkString("\n\n")}\n\nend $P\n"

  def obligations(n: Node[?, ?]): List[Obligation] =
    val own = List(
      Obligation("inv_init", "∀ s, init s → invariant s", s"Every initial state of ${n.id} satisfies its property.", step = false),
      Obligation("inv_next", "∀ s e t, invariant s → next s e t → invariant t", s"Every step of ${n.id} preserves its property.", step = true)
    )
    val link = project.parentOf(n).toList.flatMap { p =>
      List(
        Obligation("link_init", s"∀ s, init s → $P.${p.id}.init (abs s)",
          s"Every initial state of ${n.id} is an initial state of ${p.id}.", step = false),
        Obligation("link_next", s"∀ s e t, invariant s → next s e t → FrFlow.Step $P.${p.id}.machine (abs s) (event s e) (abs t)",
          s"Every step of ${n.id} is a step of ${p.id}, or changes nothing ${p.id} sees.", step = true)
      )
    }
    own ++ link

  def spec(n: Node[?, ?]): String =
    val sb = StringBuilder()
    sb ++= Header
    sb ++= s"import ${project.parentOf(n).fold(s"FrFlowGen.$P.Types")(p => specModule(p.id))}\n\n"
    sb ++= Preamble
    sb ++= s"namespace $P.${n.id}\n\n"
    sb ++= s"/-! # ${n.id}\n\n${n.statement.replace("-/", "- /")}\n-/\n\n"
    def d(name: String, l: Lifted[?]) = sb ++= s"@[frflow_defs] def $name : ${l.leanType} :=\n  ${l.lean}\n\n"
    d("init", n.init)
    d("next", n.next)
    d("invariant", n.property)
    n.parent.foreach { link =>
      d("abs", link.abs)
      d("event", link.event)
    }
    sb ++= s"@[frflow_defs] abbrev machine : FrFlow.Machine := ⟨${n.stateType}, ${n.eventType}, init, next⟩\n\n"
    sb ++= "namespace Obl\n\n"
    obligations(n).foreach(o => sb ++= s"/-- ${o.description} -/\n@[frflow_defs] def ${o.name} : Prop :=\n  ${o.statement}\n\n")
    sb ++= s"end Obl\n\nend $P.${n.id}\n"
    sb.result()

  def proofScript(o: Obligation): String =
    if o.step then s"  unfold Obl.${o.name}\n  intro s e t h hstep\n  frflow_cases hstep\n  all_goals frflow_auto\n"
    else s"  unfold Obl.${o.name}\n  frflow_auto\n"

  def auto(n: Node[?, ?]): String =
    val sb = StringBuilder()
    sb ++= Header + s"import ${specModule(n.id)}\n\n" + Preamble
    sb ++= s"namespace $P.${n.id}.Auto\nopen $P.${n.id}\n\n"
    obligations(n).filterNot(o => isAuthored(n.id, o.name)).foreach { o =>
      sb ++= s"theorem ${o.name} : Obl.${o.name} := by\n${proofScript(o)}\n"
    }
    sb ++= s"end $P.${n.id}.Auto\n"
    sb.result()

  private def ref(n: Node[?, ?], o: String) = s"$P.${n.id}.${if isAuthored(n.id, o) then "Proofs" else "Auto"}.$o"

  def theorems(n: Node[?, ?]): String =
    val root = project.root
    val sb = StringBuilder()
    sb ++= Header + s"import ${autoModule(n.id)}\n"
    if authored.get(n.id).exists(_.nonEmpty) then sb ++= s"import ${proofsModule(n.id)}\n"
    project.parentOf(n).foreach(p => sb ++= s"import ${theoremsModule(p.id)}\n")
    sb ++= "\n" + Preamble + s"namespace $P.${n.id}\n\n"
    sb ++= s"/-- The property of ${n.id} holds in every reachable state. -/\n"
    sb ++= s"theorem holds : FrFlow.Invariant machine invariant :=\n  FrFlow.Invariant.of_inductive ${ref(n, "inv_init")} ${ref(n, "inv_next")}\n\n"
    project.parentOf(n).foreach { p =>
      sb ++= s"/-- ${n.id} specializes ${p.id}. -/\n"
      sb ++= s"def link : FrFlow.Link machine $P.${p.id}.machine where\n"
      sb ++= s"  abs := abs\n  event := event\n  inv := invariant\n  inv_holds := holds\n"
      sb ++= s"  init_ok := ${ref(n, "link_init")}\n  next_ok := ${ref(n, "link_next")}\n\n"
    }
    val chain = project.path(n).drop(1).reverse.foldLeft("s")((acc, a) => s"$P.${a.id}.abs ($acc)")
    sb ++= s"/-- The root theorem holds in ${n.id}: ${root.statement.replace("-/", "- /")} -/\n"
    sb ++= s"theorem root : FrFlow.Invariant machine (fun s => $P.${root.id}.invariant ($chain)) :=\n"
    sb ++= project.parentOf(n).fold("  holds\n")(p => s"  link.transfer $P.${p.id}.root\n")
    sb ++= s"\nend $P.${n.id}\n"
    sb.result()

  def auditedTheorems(n: Node[?, ?]): List[String] = List(s"$P.${n.id}.holds", s"$P.${n.id}.root")

  def audit(n: Node[?, ?]): String =
    Header + s"import ${theoremsModule(n.id)}\n\n" + auditedTheorems(n).map(t => s"#print axioms $t\n").mkString

  def proofFile(n: Node[?, ?], names: List[String], existing: Option[String]): String =
    val stubs = obligations(n).filter(o => names.contains(o.name)).map { o =>
      s"/-- ${o.description} -/\ntheorem ${o.name} : Obl.${o.name} := by\n  unfold Obl.${o.name}\n  sorry\n\n"
    }.mkString
    val footer = s"end $P.${n.id}.Proofs\n"
    existing match
      case Some(src) if src.contains(footer.trim) => src.replace(footer.trim, stubs + footer.trim)
      case Some(src) => src + "\n" + stubs
      case None =>
        s"""import ${specModule(n.id)}
           |
           |/-! Authored proofs for ${n.id}: only obligations `frflow_auto` does not prove.
           |Each theorem must state exactly `Obl.<name>`. -/
           |
           |$Preamble
           |namespace $P.${n.id}.Proofs
           |open $P.${n.id}
           |
           |$stubs$footer""".stripMargin

  def lakefile(kernelPath: String): String =
    s"""name = "${P.toLowerCase}"
       |defaultTargets = ["FrFlowGen"]
       |
       |[[require]]
       |name = "frflow"
       |path = "$kernelPath"
       |
       |[[lean_lib]]
       |name = "FrFlowGen"
       |globs = ["FrFlowGen.+"]
       |
       |[[lean_lib]]
       |name = "Proofs"
       |globs = ["Proofs.+"]
       |""".stripMargin
