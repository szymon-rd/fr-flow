package frflow

import scala.collection.mutable

/** The proof obligation of a refining or contract node. */
final case class Obligation(name: String, statement: String, description: String)

/** Generates the Lean of a knowledge base. Layout, relative to the Lean workspace:
  *
  *   - `FrFlowGen/<KB>/Domain.lean`         domain types and defined functions
  *   - `FrFlowGen/<KB>/<Node>/Spec.lean`    the node's definitions and its obligation
  *   - `FrFlowGen/<KB>/<Node>/Auto.lean`    `frflow_auto` on the obligation, unless proven by hand
  *   - `FrFlowGen/<KB>/<Node>/Theorems.lean` `link` and `root`
  *   - `FrFlowAudit/<KB>/<Node>.lean`       axioms of `root`
  *
  * Every declaration of a node takes the node's parameters, explicitly: its
  * opaque types and its parameters.
  *
  * @param authored (node, obligation) proven by a theorem of that name in `Proofs/<KB>/<Node>.lean`
  */
object Generate:
  /** Names the generated Lean binds itself; a parameter or opaque type with one of them would be captured. */
  val reserved: Set[String] =
    Set("m", "f", "h", "p", "spec", "abs", "post", "toRoot", "rootSpec", "link", "root", "Obl", "Type", "Prop",
      "some", "none", "True", "False", "true", "false", "max", "min", "decide", "List", "Option", "Int", "Nat", "Bool", "String",
      "Prod", "Exists", "Eq", "Ne", "Not", "And", "Or", "Iff", "id", "ite", "Classical", "Unit", "FrFlow") ++ (0 to 9).map(i => s"x$i")

final class Generate(kb: KnowledgeBase, authored: Set[(String, String)] = Set.empty):
  /** Whether the proof file of `n` proves its obligation `name`. */
  def isAuthored(n: Node[?], name: String): Boolean = authored((n.id, name))
  private def authoredLink(id: String): Boolean = authored((id, "link"))
  private val K = kb.name

  def specModule(id: String) = s"FrFlowGen.$K.$id.Spec"
  def autoModule(id: String) = s"FrFlowGen.$K.$id.Auto"
  def theoremsModule(id: String) = s"FrFlowGen.$K.$id.Theorems"
  def proofsModule(id: String) = s"Proofs.$K.$id"
  def specPath(id: String) = s"FrFlowGen/$K/$id/Spec.lean"
  def autoPath(id: String) = s"FrFlowGen/$K/$id/Auto.lean"
  def theoremsPath(id: String) = s"FrFlowGen/$K/$id/Theorems.lean"
  def proofsPath(id: String) = s"Proofs/$K/$id.lean"
  /** Lemmas the proof files of this knowledge base share. */
  def lemmasModule = s"Proofs.$K.Lemmas"
  def lemmasPath = s"Proofs/$K/Lemmas.lean"
  def auditPath(id: String) = s"FrFlowAudit/$K/$id.lean"
  def generatedDirs = List(s"FrFlowGen/$K", s"FrFlowAudit/$K")

  private val Header = "-- GENERATED by FrFlow from the Scala model. Do not edit.\n\n"
  private val Preamble = "set_option autoImplicit false\nset_option linter.unusedVariables false\nnoncomputable section\nopen Classical\n\n"

  // ---------------------------------------------------------------------------
  // Contexts: the opaque types and parameters a declaration depends on
  // ---------------------------------------------------------------------------

  final case class Ctx(opaques: List[String], params: List[String]):
    def ++(o: Ctx): Ctx = Ctx((opaques ++ o.opaques).distinct, (params ++ o.params).distinct)
    def without(names: Set[String]): Ctx = Ctx(opaques.filterNot(names), params.filterNot(names))

  private object Ctx:
    val empty: Ctx = Ctx(Nil, Nil)

  private val paramTypes: Map[String, String] =
    (kb.nodes.flatMap(_.lifted) ++ kb.defs.map(_.lifted)).flatMap(_.paramRefs).toMap
  private val defByName: Map[String, Def[?]] = kb.defs.map(d => d.name -> d).toMap

  private val defCtxCache = mutable.Map.empty[String, Ctx]

  private def defCtx(d: Def[?]): Ctx =
    defCtxCache.getOrElseUpdate(d.name, {
      defCtxCache(d.name) = Ctx.empty // recursion
      ctx(d.lifted, Set(d.name))
    })

  /** Context of a lifted expression: what it mentions, and what the functions it calls need. */
  def ctx(l: Lifted[?], self: Set[String] = Set.empty): Ctx =
    val own = Ctx(l.opaques, l.paramRefs.map(_._1))
    val viaDefs = l.defs.filterNot(d => self(d.name)).map(defCtx).foldLeft(Ctx.empty)(_ ++ _)
    own ++ viaDefs

  def binders(c: Ctx): String =
    val ts = if c.opaques.isEmpty then Nil else List(s"(${c.opaques.mkString(" ")} : Type)")
    val ps = c.params.map(p => s"($p : ${paramTypes.getOrElse(p, "_")})")
    (ts ++ ps).mkString(" ")

  def args(c: Ctx): String = (c.opaques ++ c.params).mkString(" ")

  private def app(f: String, c: Ctx): String = if args(c).isEmpty then f else s"($f ${args(c)})"

  /** Replaces `⟦f⟧` by `f` applied to the parameters it takes. */
  def resolve(lean: String): String =
    """⟦([^⟧]+)⟧""".r.replaceAllIn(lean, m =>
      scala.util.matching.Regex.quoteReplacement(defByName.get(m.group(1)).fold(s"$K.${m.group(1)}")(d => app(s"$K.${d.name}", defCtx(d)))))

  /** Context of a node: what all its declarations take. */
  def nodeCtx(n: Node[?]): Ctx = n.expected.map(e => ctx(e._2)).foldLeft(ownCtx(n))(_ ++ _)

  private def ownCtx(n: Node[?]): Ctx = n.kind match
    case NodeKind.Root     => ctx(n.spec.get)
    case NodeKind.Refine   => ctx(n.spec.get) ++ ctx(n.abs.get) ++ nodeCtx(n.parent.get)
    case NodeKind.Contract =>
      (ctx(n.post.get) :: n.abs.toList.map(ctx(_)) ++ formalKeeps(n).flatMap((i, v) => List(ctx(i.spec.get), ctx(v))) ++
        provenImpl(n).map(defCtx)).reduce(_ ++ _) ++ nodeCtx(n.parent.get)
    case NodeKind.Design | NodeKind.Invariant => Ctx.empty
    case NodeKind.Instantiate =>
      val substituted = n.substs.map(_.name).toSet
      n.substs.flatMap(_.term).map(ctx(_)).foldLeft(nodeCtx(n.parent.get).without(substituted))(_ ++ _)

  // ---------------------------------------------------------------------------
  // Files
  // ---------------------------------------------------------------------------

  def files: Map[String, String] =
    val perNode = kb.nodes.filter(formal).flatMap { n =>
      List(specPath(n.id) -> spec(n), autoPath(n.id) -> auto(n), theoremsPath(n.id) -> theorems(n), auditPath(n.id) -> audit(n)) ++
        extraObligations(n).map(o => oblPath(n.id, o.name) -> oblFile(n, o)) ++
        saysNothing(n).map(e => oblPath(n.id, e.obligation.name) -> attempt(n, e.obligation)) ++
        rootImplFile(n).map(oblPath(n.id, "rootImpl") -> _) ++
        idle(n).map((o, _) => oblPath(n.id, o.name) -> attempt(n, o))
    }
    (s"FrFlowGen/$K/Domain.lean" -> domain :: perNode).toMap

  /** Lean of the domain types and functions a node's own expressions use. */
  def declarationsUsedBy(n: Node[?]): List[String] =
    val defs = mutable.LinkedHashMap.empty[String, Def[?]]
    def visit(d: Def[?]): Unit = if !defs.contains(d.name) then { defs(d.name) = d; d.lifted.defs.foreach(visit) }
    // What the node's own lambdas call, the invariants' rules it keeps, and its proven implementation:
    // a change to any of them re-runs its check.
    (n.lifted ++ formalKeeps(n).flatMap(_._1.spec)).flatMap(_.defs).foreach(visit)
    provenImpl(n).foreach(visit)
    val ls = n.lifted ++ formalKeeps(n).flatMap(_._1.spec) ++ defs.values.map(_.lifted)
    ls.flatMap(_.types).map(_.lean).distinct ++ defs.values.map(d => resolve(d.lifted.lean))

  /** What a node uses, as written in Scala: the domain types (theirs, and those it substitutes) and
    * the definitions, however nested. Part of what a decision is bound to; unlike the generated Lean,
    * it does not change when FrFlow's translation does.
    */
  def sourcesUsedBy(n: Node[?]): List[String] =
    val defs = mutable.LinkedHashMap.empty[String, Def[?]]
    def visit(d: Def[?]): Unit = if !defs.contains(d.name) then { defs(d.name) = d; d.lifted.defs.foreach(visit) }
    n.referenced.flatMap(_.defs).foreach(visit)
    val types = (n.referenced ++ defs.values.map(_.lifted)).flatMap(_.types) ++ n.substs.flatMap(_.types)
    types.map(t => if t.scala.nonEmpty then t.scala else t.lean).distinct ++ defs.values.map(d => s"${d.name} = ${d.lifted.source}")

  def domain: String =
    val defs = kb.defs.map { d =>
      val b = binders(defCtx(d))
      s"@[frflow_defs] def ${d.name}${if b.isEmpty then "" else " " + b} : ${d.lifted.leanType} :=\n  ${resolve(d.lifted.lean)}"
    }
    Header + "import FrFlow\n\n" + Preamble + s"namespace $K\n\n" + (kb.types.map(_.lean) ++ defs).mkString("\n\n") + s"\n\nend $K\n"

  /** Nodes with a formal model, which get Lean. */
  def formal(n: Node[?]): Boolean = n.kind != NodeKind.Design && n.kind != NodeKind.Invariant && n.formal

  /** The invariants a contract keeps in Lean, each with the contract's view of a call. */
  def formalKeeps(n: Node[?]): List[(Node[?], Lifted[?])] =
    if !n.formal then Nil
    else n.kept.collect { case Keep(i, Some(v), _) if i.formal && v.body.nonEmpty && i.spec.exists(_.body.nonEmpty) => (i, v) }

  /** The file an obligation, or a check that the node says nothing, is proven in. */
  def oblPath(id: String, name: String) = s"FrFlowGen/$K/$id/${name.capitalize}.lean"

  /** The implementation of a contract, when it is a `define` Lean can prove things about. */
  def provenImpl(n: Node[?]): Option[Def[?]] =
    if !n.formal || n.kind != NodeKind.Contract then None else kb.implementation(n).flatMap(_.proven)

  private def at(n: Node[?])(f: String): String = { val a = args(nodeCtx(n)); if a.isEmpty then f else s"$f $a" }
  private def pat(p: Node[?])(f: String): String = { val a = args(nodeCtx(p)); if a.isEmpty then q(p, f) else s"${q(p, f)} $a" }

  /** `∀ ctx, ∀ vars, premise → conclusion`, over the node's opaque types and parameters. */
  private def stated(n: Node[?], vars: String, premise: Option[String], conclusion: String): String =
    val b = binders(nodeCtx(n))
    (if b.isEmpty then "" else s"∀ $b, ") + (if vars.isEmpty then "" else s"∀ $vars, ") + premise.fold("")(_ + " → ") + conclusion

  /** What a node claims, from what it says (`premise`): its link, each invariant it keeps, its proven
    * implementation. `vacuous` is why the claim says nothing if it holds without the premise.
    */
  private final case class Claim(name: String, vars: String, premise: Option[String], conclusion: String, description: String,
      vacuous: String = "")

  private def claims(n: Node[?]): List[Claim] =
    val link = n.parent.filter(_ => n.kind == NodeKind.Refine || n.kind == NodeKind.Contract).map { p =>
      val target = if n.abs.isDefined then s"(${at(n)("abs")} m)" else "m"
      Claim("link", s"(m : ${modelType(n)})", Some(s"${at(n)("spec")} m"), s"${pat(p)("spec")} $target",
        s"Every model that meets ${n.id} meets ${p.id}.", s"vacuous: ${p.id} holds whatever ${n.id} says")
    }
    def call(ts: List[String]) = (ts.zipWithIndex.map((t, i) => s"(x$i : $t)").mkString(" "), ts.indices.map(i => s"x$i").mkString(" "))
    val keeps = formalKeeps(n).map { (inv, _) =>
      val (vars, xs) = call(n.post.get.params.map(_._2))
      Claim(s"inv_${inv.id}", vars, Some(s"${at(n)("post")} $xs"),
        s"∀ p, p ∈ ${at(n)(s"view_${inv.id}")} $xs → ${at(n)(s"rule_${inv.id}")} p.1 p.2", s"Every call ${n.id} allows keeps ${inv.id}.",
        s"kept in name only: the pairs the view lists meet ${inv.id}'s rule whatever the call returns")
    }
    val impl = provenImpl(n).map { d =>
      val (vars, xs) = call(n.post.get.params.init.map(_._2))
      Claim("impl", vars, None, s"${at(n)("post")} $xs (${resolve(s"⟦${d.name}⟧")} $xs)", s"Every result of ${d.name} meets ${n.id}.")
    }
    // A proof the agent wrote may rest on a contradiction automation did not find: then something
    // must meet the node. A proven implementation at or below it is that witness (the links between
    // prove it meets the node, under the meanings fixed on the way).
    val witnessed = kb.nodes.exists(c => provenImpl(c).isDefined && kb.path(c).exists(_ eq n))
    val feasible = Option.when(authoredLink(n.id) && !witnessed && link.isDefined)(
      Claim("feasible", "", None, s"∃ (m : ${modelType(n)}), ${at(n)("spec")} m", s"Some model meets ${n.id}: its authored link does not rest on a contradiction."))
    // What the developer expects of every model of the node: their understanding, checked.
    val expects = Option.when(n.kind == NodeKind.Root || n.kind == NodeKind.Refine || n.kind == NodeKind.Contract)(n.expected).toList.flatten
      .zipWithIndex.map { case ((statement, _), i) =>
        Claim(s"expect_$i", s"(m : ${modelType(n)})", Some(s"${at(n)("spec")} m"), s"${at(n)(s"expected_$i")} m", statement,
          s"it holds of every model, whatever ${n.id} says: it checks nothing")
      }
    link.toList ++ keeps ++ impl ++ feasible ++ expects

  /** What a formal node must prove: its link, the invariants it keeps, its proven implementation. */
  def obligations(n: Node[?]): List[Obligation] =
    claims(n).map(c => Obligation(c.name, stated(n, c.vars, c.premise, c.conclusion), c.description))
  def obligation(n: Node[?]): Option[Obligation] = obligations(n).find(_.name == "link")
  /** Obligations proven in files of their own: all but the link. */
  def extraObligations(n: Node[?]): List[Obligation] = obligations(n).filterNot(_.name == "link")

  /** A statement that, if `frflow_auto` proves it, shows the node says nothing: `fails` is the claim
    * that then fails (the link fails the node), with why.
    */
  final case class Empty(obligation: Obligation, fails: String, why: String, message: String)

  /** Each claim holding without its premise (a vacuous link; an invariant kept in name only); no model
    * meeting the node; the root holding for every model of the node, decided by an `abs` or a
    * substitution above. Each is tried by `frflow_auto`, which can miss one.
    */
  def saysNothing(n: Node[?]): List[Empty] =
    val m = s"(m : ${modelType(n)})"
    val vacuous = claims(n).filter(_.premise.nonEmpty).map { c =>
      Empty(Obligation(s"vacuous_${c.name}", stated(n, c.vars, None, c.conclusion), s"${c.description} Without ${n.id}'s own statement."),
        c.name, c.vacuous, s"${c.name} proves nothing: it holds whatever ${n.id} says")
    }
    val node = Option.when(n.kind == NodeKind.Refine || n.kind == NodeKind.Contract)(List(
      Empty(Obligation("unsat", stated(n, m, None, s"¬ ${at(n)("spec")} m"), s"No model meets ${n.id}."), "link",
        s"unsatisfiable: no model meets ${n.id}", s"${n.id} is contradictory: no model meets it, so every link below it holds and says nothing")) ++
      n.parent.filter(_.kind != NodeKind.Root).map(_ =>
        Empty(Obligation("rootTrivial", stated(n, m, None, s"${at(n)("rootSpec")} (${at(n)("toRoot")} m)"),
          s"The root holds for every model of ${n.id}, whatever ${n.id} says."), "link", s"the root holds whatever ${n.id} says",
          s"the root holds for every model of ${n.id}, whatever its spec: an abs or a substitution above decides it, so the root theorem says nothing about ${n.id}"))
    ).getOrElse(Nil)
    vacuous ++ node

  /** The contract met by doing nothing (returning `[]` or `none`, or the input unchanged) on every
    * call, as `frflow_auto` may show: what it then leaves to the examples.
    */
  def idle(n: Node[?]): Option[(Obligation, String)] =
    Option.when(formal(n) && n.kind == NodeKind.Contract)(n.post.get.params.map(_._2)).flatMap { ts =>
      val r = ts.last
      val ins = ts.init
      val (vars, xs) = (ins.zipWithIndex.map((t, i) => s"(x$i : $t)").mkString(" "), ins.indices.map(i => s"x$i").mkString(" "))
      val nothing =
        if r.startsWith("(List ") then Some("[]" -> "returning nothing")
        else if r.startsWith("(Option ") then Some("none" -> "returning None")
        else ins.indexOf(r) match { case -1 => None; case i => Some(s"x$i" -> "returning its input unchanged") }
      nothing.map((v, what) => (Obligation("idle", stated(n, vars, None, s"${at(n)("post")} $xs $v"), s"${n.id} is met by $what."), what))
    }

  /** The proof of an obligation in a file of its own: the authored theorem of that name, or frflow_auto. */
  def oblFile(n: Node[?], o: Obligation): String =
    val ns = s"$K.${n.id}.${o.name.capitalize}"
    val mine = isAuthored(n, o.name)
    val proof = if mine then s"$K.${n.id}.Proofs.${o.name}" else s"by\n  unfold Obl.${o.name}\n  frflow_auto"
    Header + s"import ${specModule(n.id)}\n" + (if mine then s"import ${proofsModule(n.id)}\n" else "") + "\n" + Preamble +
      s"namespace $ns\nopen $K.${n.id}\n\ntheorem ${o.name} : Obl.${o.name} := $proof\n\n#print axioms ${o.name}\n\nend $ns\n"

  def oblModule(id: String, name: String) = s"FrFlowGen.$K.$id.${name.capitalize}"

  /** The root theorem of a proven implementation: the root holds of the code itself, composed from
    * the node's `root` and its `impl` proof.
    */
  def rootImplFile(n: Node[?]): Option[String] = provenImpl(n).map { d =>
    val a = args(nodeCtx(n))
    val impl = resolve(s"⟦${d.name}⟧")
    val statement = stated(n, "", None, s"${at(n)("rootSpec")} (${at(n)("toRoot")} $impl)")
    val intro = if a.isEmpty then "" else s"  intro $a\n"
    Header + s"import ${theoremsModule(n.id)}\nimport ${oblModule(n.id, "impl")}\n\n" + Preamble +
      s"namespace $K.${n.id}.RootImpl\nopen $K.${n.id}\n\n/-- The root holds of ${d.name}, the code. -/\n" +
      s"theorem root_impl : $statement := by\n$intro  exact ${if a.isEmpty then "root" else s"root $a"} _ ($K.${n.id}.Impl.impl${if a.isEmpty then "" else s" $a"})\n\n" +
      s"#print axioms root_impl\n\nend $K.${n.id}.RootImpl\n"
  }

  /** What frflow_auto tries for a check that the node says nothing. */
  def attempt(n: Node[?], o: Obligation): String =
    val ns = o.name.capitalize
    Header + s"import ${specModule(n.id)}\n\n" + Preamble + s"namespace $K.${n.id}.$ns\nopen $K.${n.id}\n\n" +
      s"theorem ${o.name} : Obl.${o.name} := by\n  unfold Obl.${o.name}\n  frflow_auto\n\nend $K.${n.id}.$ns\n"

  private def modelType(n: Node[?]): String = n.kind match
    case NodeKind.Design | NodeKind.Invariant => "Unit"
    case NodeKind.Root | NodeKind.Refine => n.spec.get.params.head._2
    case NodeKind.Contract           => n.post.get.params.map(_._2).mkString(" → ")
    case NodeKind.Instantiate        => "_"

  private def q(n: Node[?], decl: String) = s"$K.${n.id}.$decl"


  def spec(n: Node[?]): String =
    val c = nodeCtx(n)
    val b = if binders(c).isEmpty then "" else " " + binders(c)
    val a = args(c)
    def at(f: String) = if a.isEmpty then f else s"$f $a"
    val sb = StringBuilder()
    sb ++= Header + s"import ${n.parent.fold(s"FrFlowGen.$K.Domain")(p => specModule(p.id))}\n\n" + Preamble
    sb ++= s"namespace $K.${n.id}\n\n"
    def d(name: String, tpe: String, body: String) =
      sb ++= s"@[frflow_defs] def $name$b${if tpe.isEmpty then "" else s" : $tpe"} :=\n  $body\n\n"
    val m = modelType(n)
    n.kind match
      case NodeKind.Design | NodeKind.Invariant => ()
      case NodeKind.Root =>
        d("spec", s"$m → Prop", resolve(n.spec.get.lean))
        d("toRoot", "", s"fun (m : $m) => m")
        d("rootSpec", "", at("spec"))
      case NodeKind.Refine =>
        val p = n.parent.get
        val pa = args(nodeCtx(p))
        def pat(f: String) = if pa.isEmpty then q(p, f) else s"(${q(p, f)} $pa)"
        d("spec", s"$m → Prop", resolve(n.spec.get.lean))
        d("abs", n.abs.get.leanType, resolve(n.abs.get.lean))
        d("toRoot", "", s"fun (m : $m) => ${pat("toRoot")} (${at("abs")} m)")
        d("rootSpec", "", pat("rootSpec"))
      case NodeKind.Contract =>
        val p = n.parent.get
        val pa = args(nodeCtx(p))
        def pat(f: String) = if pa.isEmpty then q(p, f) else s"(${q(p, f)} $pa)"
        val post = n.post.get
        val ins = post.params.init
        d("post", post.leanType, resolve(post.lean))
        formalKeeps(n).foreach { (inv, v) =>
          d(s"rule_${inv.id}", inv.spec.get.leanType, resolve(inv.spec.get.lean))
          d(s"view_${inv.id}", v.leanType, resolve(v.lean))
        }
        val vars = ins.indices.map(i => s"x$i").mkString(" ")
        d("spec", s"($m) → Prop", s"fun (f : $m) => ∀ ${ins.zipWithIndex.map((t, i) => s"(x$i : ${t._2})").mkString(" ")}, ${at("post")} $vars (f $vars)")
        // A contract with a signature of its own maps its implementations to the parent's model.
        n.abs.foreach(a => d("abs", a.leanType, resolve(a.lean)))
        d("toRoot", "", if n.abs.isDefined then s"fun (m : $m) => ${pat("toRoot")} (${at("abs")} m)" else s"fun (m : $m) => ${pat("toRoot")} m")
        d("rootSpec", "", pat("rootSpec"))
      case NodeKind.Instantiate =>
        n.substs.filterNot(_.isType).foreach { s =>
          val t = s.term.get
          val sb2 = binders(ctx(t))
          sb ++= s"@[frflow_defs] def s_${s.name}${if sb2.isEmpty then "" else " " + sb2} : ${t.leanType} :=\n  ${resolve(t.lean)}\n\n"
        }
        val th = theta(n)
        val p = n.parent.get
        d("spec", "", s"${q(p, "spec")} $th")
        d("toRoot", "", s"${q(p, "toRoot")} $th")
        d("rootSpec", "", s"${q(p, "rootSpec")} $th")
    if n.kind == NodeKind.Root || n.kind == NodeKind.Refine || n.kind == NodeKind.Contract then
      n.expected.zipWithIndex.foreach { case ((_, l), i) => d(s"expected_$i", l.leanType, resolve(l.lean)) }
    (obligations(n) ++ saysNothing(n).map(_.obligation) ++ idle(n).map(_._1)).foreach { o =>
      sb ++= s"namespace Obl\n\n/-- ${o.description} -/\n@[frflow_defs] def ${o.name} : Prop :=\n  ${o.statement}\n\nend Obl\n\n"
    }
    sb ++= s"end $K.${n.id}\n"
    sb.result()

  /** Named arguments that instantiate the parent's declarations. */
  def theta(n: Node[?]): String =
    val pc = nodeCtx(n.parent.get)
    val byName = n.substs.map(s => s.name -> s).toMap
    val types = pc.opaques.map(o => s"($o := ${byName.get(o).fold(o)(_.lean)})")
    val params = pc.params.map { p =>
      byName.get(p).flatMap(_.term) match
        case Some(t) => s"($p := ${app(s"s_$p", ctx(t))})"
        case None    => s"($p := $p)"
    }
    (types ++ params).mkString(" ")

  def auto(n: Node[?]): String =
    val body = obligation(n).filterNot(_ => authoredLink(n.id)).fold("") { o =>
      s"theorem ${o.name} : Obl.${o.name} := by\n  unfold Obl.${o.name}\n  frflow_auto\n\n"
    }
    Header + s"import ${specModule(n.id)}\n\n" + Preamble + s"namespace $K.${n.id}.Auto\nopen $K.${n.id}\n\n$body" + s"end $K.${n.id}.Auto\n"

  def theorems(n: Node[?]): String =
    val c = nodeCtx(n)
    val b = if binders(c).isEmpty then "" else " " + binders(c)
    val a = args(c)
    def at(f: String) = if a.isEmpty then f else s"($f $a)"
    val sb = StringBuilder()
    sb ++= Header + s"import ${autoModule(n.id)}\n"
    if authoredLink(n.id) then sb ++= s"import ${proofsModule(n.id)}\n"
    n.parent.foreach(p => sb ++= s"import ${theoremsModule(p.id)}\n")
    sb ++= "\n" + Preamble + s"namespace $K.${n.id}\n\n"
    val m = if n.kind == NodeKind.Instantiate then "m" else s"(m : ${modelType(n)})"
    val rootStatement = s"∀ $m, ${at("spec")} m → ${at("rootSpec")} (${at("toRoot")} m)"
    val proofOfRoot = n.kind match
      case NodeKind.Root | NodeKind.Design | NodeKind.Invariant => "fun m h => h"
      case NodeKind.Instantiate => s"${q(n.parent.get, "root")} ${theta(n)}"
      case _ =>
        val p = n.parent.get
        val pa = args(nodeCtx(p))
        def pat(f: String) = if pa.isEmpty then q(p, f) else s"(${q(p, f)} $pa)"
        val target = if n.abs.isDefined then s"(${at("abs")} m)" else "m"
        val ref = s"$K.${n.id}.${if authoredLink(n.id) then "Proofs" else "Auto"}.link"
        sb ++= s"/-- ${obligation(n).get.description} -/\n"
        sb ++= s"theorem link$b : ∀ $m, ${at("spec")} m → ${pat("spec")} $target :=\n  ${if a.isEmpty then ref else s"$ref $a"}\n\n"
        s"fun m h => ${pat("root")} $target (${at("link")} m h)"
    sb ++= s"/-- The root theorem holds for every model of ${n.id}. -/\n"
    sb ++= s"theorem root$b : $rootStatement :=\n  $proofOfRoot\n\nend $K.${n.id}\n"
    sb.result()

  /** The statement of the node's `root` theorem, as Lean source. */
  def rootTheorem(n: Node[?]): String =
    val t = theorems(n)
    val from = t.indexOf("theorem root")
    t.substring(from, t.indexOf(" :=", from))

  def auditedTheorems(n: Node[?]): List[String] = List(q(n, "root"))

  def audit(n: Node[?]): String =
    Header + s"import ${theoremsModule(n.id)}\n\n" + auditedTheorems(n).map(t => s"#print axioms $t\n").mkString

  def proofFile(n: Node[?]): String =
    s"""import ${specModule(n.id)}
       |
       |/-! Authored proofs of the obligations of ${n.id}. Each states exactly its `Obl`. -/
       |
       |$Preamble
       |namespace $K.${n.id}.Proofs
       |open $K.${n.id}
       |
       |theorem link : Obl.link := by
       |  unfold Obl.link
       |  sorry
       |${if !kb.nodes.exists(c => provenImpl(c).isDefined && kb.path(c).exists(_ eq n)) then "\n/-- Something meets the node: the proof above does not rest on a contradiction. -/\ntheorem feasible : Obl.feasible := by\n  unfold Obl.feasible\n  sorry\n" else ""}
       |end $K.${n.id}.Proofs
       |""".stripMargin

  def lakefile(kernelPath: String): String =
    s"""name = "${K.toLowerCase}"
       |defaultTargets = ["FrFlowGen"]
       |
       |[[require]]
       |name = "frflow"
       |path = "$kernelPath"
       |
       |[[lean_lib]]
       |name = "FrFlowGen"
       |globs = ["FrFlowGen.+"]
       |
       |[[lean_lib]]
       |name = "Proofs"
       |globs = ["Proofs.+"]
       |""".stripMargin
