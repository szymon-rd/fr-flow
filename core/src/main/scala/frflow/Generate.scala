package frflow

import scala.collection.mutable

/** The proof obligation of a refining or contract node. */
final case class Obligation(name: String, statement: String, description: String)

/** Generates the Lean of a knowledge base. Layout, relative to the Lean workspace:
  *
  *   - `FrFlowGen/<KB>/Domain.lean`         domain types and defined functions
  *   - `FrFlowGen/<KB>/<Node>/Spec.lean`    the node's definitions and its obligation
  *   - `FrFlowGen/<KB>/<Node>/Auto.lean`    `frflow_auto` on the obligation, unless proven by hand
  *   - `FrFlowGen/<KB>/<Node>/Theorems.lean` `link` and `root`
  *   - `FrFlowGen/<KB>/<Node>/Eval.lean`    the examples, evaluated
  *   - `FrFlowGen/<KB>/<Node>/Checks.lean`  everything else checked of the node, with the axioms each uses
  *
  * Every declaration of a node takes the node's parameters, explicitly: its
  * opaque types and its parameters.
  *
  * @param authored (node, obligation) proven by a theorem of that name in `Proofs/<KB>/<Node>.lean`
  */
object Generate:
  /** Names the generated Lean binds itself; a parameter or opaque type with one of them would be captured. */
  val reserved: Set[String] =
    Set("m", "f", "h", "p", "spec", "abs", "post", "toRoot", "rootSpec", "link", "root", "Obl", "Type", "Prop",
      "some", "none", "True", "False", "true", "false", "max", "min", "decide", "List", "Option", "Int", "Nat", "Bool", "String",
      "Prod", "Exists", "Eq", "Ne", "Not", "And", "Or", "Iff", "id", "ite", "Classical", "Unit", "FrFlow") ++ (0 to 9).map(i => s"x$i")

  /** How many probes of a contract Lean evaluates, beside its examples. */
  val Probes = 6

  /** The numbers a value holds, however nested: the boundaries a probe tries. */
  def numbers(v: Any): List[BigInt] = v match
    case i: Int     => List(BigInt(i))
    case l: Long    => List(BigInt(l))
    case b: BigInt  => List(b)
    case l: Iterable[?] => l.toList.flatMap(numbers)
    case Some(x)    => numbers(x)
    case p: Product => p.productIterator.toList.flatMap(numbers)
    case _          => Nil

  /** Values of the same type near `v`: a number at the boundaries (`nums`, and next to it), a list
    * emptied, shortened, reversed or with its head again, a string emptied, an option empty, a case
    * class or tuple with one field changed so. What the examples do not reach, the translation is
    * checked on.
    */
  def near(v: Any, nums: List[BigInt]): List[Any] =
    val out: List[Any] = v match
      case b: Boolean => List(!b)
      case i: Int     => (nums.filter(_.isValidInt).map(_.toInt) ++ List(0, i + 1, i - 1, -i))
      case l: Long    => (nums.filter(_.isValidLong).map(_.toLong) ++ List(0L, l + 1, l - 1, -l))
      case b: BigInt  => nums ++ List(BigInt(0), b + 1, b - 1, -b)
      case s: String  => List("", s + s)
      case Some(x)    => None :: near(x, nums).take(2).map(Some(_))
      case l: List[?] => if l.isEmpty then Nil else List(Nil, l.tail, l.reverse, l.head :: l)
      case p: Product if p.productArity > 0 =>
        val fields = p.productIterator.toList
        val make = p.getClass.getConstructors.find(_.getParameterCount == fields.size)
        make.toList.flatMap(k => fields.indices.flatMap(i => near(fields(i), nums).take(3).flatMap(x =>
          scala.util.Try(k.newInstance(fields.updated(i, x).map(_.asInstanceOf[AnyRef])*)).toOption)))
      case _ => Nil
    out.distinct.filter(_ != v)

final class Generate(kb: KnowledgeBase, authored: Set[(String, String)] = Set.empty):
  /** Whether the proof file of `n` proves its obligation `name`. */
  def isAuthored(n: Node[?], name: String): Boolean = authored((n.id, name))
  private def authoredLink(id: String): Boolean = authored((id, "link"))
  private val K = kb.name

  def specModule(id: String) = s"FrFlowGen.$K.$id.Spec"
  def autoModule(id: String) = s"FrFlowGen.$K.$id.Auto"
  def theoremsModule(id: String) = s"FrFlowGen.$K.$id.Theorems"
  def proofsModule(id: String) = s"Proofs.$K.$id"
  def specPath(id: String) = s"FrFlowGen/$K/$id/Spec.lean"
  def autoPath(id: String) = s"FrFlowGen/$K/$id/Auto.lean"
  def theoremsPath(id: String) = s"FrFlowGen/$K/$id/Theorems.lean"
  def proofsPath(id: String) = s"Proofs/$K/$id.lean"
  /** Lemmas the proof files of this knowledge base share. */
  def lemmasModule = s"Proofs.$K.Lemmas"
  def lemmasPath = s"Proofs/$K/Lemmas.lean"
  def checksPath(id: String) = s"FrFlowGen/$K/$id/Checks.lean"
  def generatedDirs = List(s"FrFlowGen/$K", s"FrFlowAudit/$K")

  private val Header = "-- GENERATED by FrFlow from the Scala model. Do not edit.\n\n"
  private val Preamble = "set_option autoImplicit false\nset_option linter.unusedVariables false\nnoncomputable section\nopen Classical\n\n"

  // ---------------------------------------------------------------------------
  // Contexts: the opaque types and parameters a declaration depends on
  // ---------------------------------------------------------------------------

  final case class Ctx(opaques: List[String], params: List[String]):
    def ++(o: Ctx): Ctx = Ctx((opaques ++ o.opaques).distinct, (params ++ o.params).distinct)
    def without(names: Set[String]): Ctx = Ctx(opaques.filterNot(names), params.filterNot(names))

  private object Ctx:
    val empty: Ctx = Ctx(Nil, Nil)

  private val paramTypes: Map[String, String] =
    (kb.nodes.flatMap(_.lifted) ++ kb.defs.map(_.lifted)).flatMap(_.paramRefs).toMap
  private val defByName: Map[String, Def[?]] = kb.defs.map(d => d.name -> d).toMap

  private val defCtxCache = mutable.Map.empty[String, Ctx]

  private def defCtx(d: Def[?]): Ctx = defCtxCache.synchronized {
    defCtxCache.getOrElseUpdate(d.name, {
      defCtxCache(d.name) = Ctx.empty // recursion
      ctx(d.lifted, Set(d.name))
    })
  }

  /** Context of a lifted expression: what it mentions, and what the functions it calls need. */
  def ctx(l: Lifted[?], self: Set[String] = Set.empty): Ctx =
    val own = Ctx(l.opaques, l.paramRefs.map(_._1))
    val viaDefs = l.defs.filterNot(d => self(d.name)).map(defCtx).foldLeft(Ctx.empty)(_ ++ _)
    own ++ viaDefs

  def binders(c: Ctx): String =
    val ts = if c.opaques.isEmpty then Nil else List(s"(${c.opaques.mkString(" ")} : Type)")
    val ps = c.params.map(p => s"($p : ${paramTypes.getOrElse(p, "_")})")
    (ts ++ ps).mkString(" ")

  def args(c: Ctx): String = (c.opaques ++ c.params).mkString(" ")

  private def app(f: String, c: Ctx): String = if args(c).isEmpty then f else s"($f ${args(c)})"

  /** Replaces `⟦f⟧` by `f` applied to the parameters it takes. */
  def resolve(lean: String): String =
    """⟦([^⟧]+)⟧""".r.replaceAllIn(lean, m =>
      scala.util.matching.Regex.quoteReplacement(defByName.get(m.group(1)).fold(s"$K.${m.group(1)}")(d => app(s"$K.${d.name}", defCtx(d)))))

  /** Context of a node: what all its declarations take. */
  def nodeCtx(n: Node[?]): Ctx = n.expected.map(e => ctx(e._2)).foldLeft(ownCtx(n))(_ ++ _)

  private def ownCtx(n: Node[?]): Ctx = n.kind match
    case NodeKind.Root     => ctx(n.spec.get)
    case NodeKind.Refine   => ctx(n.spec.get) ++ ctx(n.abs.get) ++ nodeCtx(n.parent.get)
    case NodeKind.Contract =>
      (ctx(n.post.get) :: n.abs.toList.map(ctx(_)) ++ n.local.toList.map(ctx(_)) ++ formalKeeps(n).flatMap((i, v) => List(ctx(i.spec.get), ctx(v))) ++
        provenImpl(n).map(defCtx)).reduce(_ ++ _) ++ n.parent.fold(Ctx.empty)(nodeCtx)
    case NodeKind.Design | NodeKind.Invariant => Ctx.empty
    case NodeKind.Instantiate =>
      val substituted = n.substs.map(_.name).toSet
      n.substs.flatMap(_.term).map(ctx(_)).foldLeft(nodeCtx(n.parent.get).without(substituted))(_ ++ _)

  // ---------------------------------------------------------------------------
  // Files
  // ---------------------------------------------------------------------------

  def files: Map[String, String] =
    val perNode = kb.nodes.filter(formal).flatMap { n =>
      List(specPath(n.id) -> spec(n), autoPath(n.id) -> auto(n), theoremsPath(n.id) -> theorems(n), checksPath(n.id) -> checks(n)) ++
        evalFile(n).map(evalPath(n.id) -> _)
    }
    (s"FrFlowGen/$K/Domain.lean" -> domain :: perNode).toMap

  /** Lean of the domain types and functions a node's own expressions use. */
  def declarationsUsedBy(n: Node[?]): List[String] =
    // What the node's own lambdas call, the invariants' rules it keeps, and its proven implementation:
    // a change to any of them re-runs its check.
    val defs = Def.closure((n.lifted ++ formalKeeps(n).flatMap(_._1.spec)).flatMap(_.defs) ++ provenImpl(n))
    val ls = n.lifted ++ formalKeeps(n).flatMap(_._1.spec) ++ defs.map(_.lifted)
    ls.flatMap(_.types).map(_.lean).distinct ++ defs.map(d => resolve(d.lifted.lean))

  /** What a node uses, as written in Scala: the domain types (theirs, and those it substitutes) and
    * the definitions, however nested. Part of what a decision is bound to; unlike the generated Lean,
    * it does not change when FrFlow's translation does.
    */
  def sourcesUsedBy(n: Node[?]): List[String] =
    val defs = Def.closure(n.referenced.flatMap(_.defs))
    val types = (n.referenced ++ defs.map(_.lifted)).flatMap(_.types) ++ n.substs.flatMap(_.types)
    types.map(t => if t.scala.nonEmpty then t.scala else t.lean).distinct ++ defs.map(d => s"${d.name} = ${d.lifted.source}")

  def domain: String =
    val defs = kb.defs.map { d =>
      val b = binders(defCtx(d))
      s"@[frflow_defs] def ${d.name}${if b.isEmpty then "" else " " + b} : ${d.lifted.leanType} :=\n  ${resolve(d.lifted.lean)}"
    }
    Header + "import FrFlow\n\n" + Preamble + s"namespace $K\n\n" + (kb.types.map(_.lean) ++ defs).mkString("\n\n") + s"\n\nend $K\n"

  /** Nodes with a formal model, which get Lean. */
  def formal(n: Node[?]): Boolean = n.kind != NodeKind.Design && n.kind != NodeKind.Invariant && n.formal

  /** The invariants a contract keeps in Lean, each with the contract's view of a call. */
  def formalKeeps(n: Node[?]): List[(Node[?], Lifted[?])] =
    if !n.formal then Nil
    else n.kept.collect { case Keep(i, Some(v), _, _) if i.formal && v.body.nonEmpty && i.spec.exists(_.body.nonEmpty) => (i, v) }

  /** The file an obligation, or a check that the node says nothing, is proven in. */


  /** The implementation of a contract, when it is a `define` Lean can prove things about. */
  def provenImpl(n: Node[?]): Option[Def[?]] =
    if !n.formal || n.kind != NodeKind.Contract then None else kb.implementation(n).flatMap(_.proven)

  private def at(n: Node[?])(f: String): String = { val a = args(nodeCtx(n)); if a.isEmpty then f else s"$f $a" }
  private def pat(p: Node[?])(f: String): String = { val a = args(nodeCtx(p)); if a.isEmpty then q(p, f) else s"${q(p, f)} $a" }

  /** `∀ ctx, ∀ vars, premise → conclusion`, over the node's opaque types and parameters. */
  private def stated(n: Node[?], vars: String, premise: Option[String], conclusion: String): String =
    val b = binders(nodeCtx(n))
    (if b.isEmpty then "" else s"∀ $b, ") + (if vars.isEmpty then "" else s"∀ $vars, ") + premise.fold("")(_ + " → ") + conclusion

  // ---------------------------------------------------------------------------
  // What a result holds: for the coverage of an invariant's view
  // ---------------------------------------------------------------------------

  /** A Lean type, read back from its text. */
  private enum LT:
    case Name(n: String)
    case ListOf(t: LT)
    case OptionOf(t: LT)
    case Prod(a: LT, b: LT)
    case Fun(text: String)

  private def parseType(t0: String): LT =
    val t = t0.trim
    def depthZero(sym: String): Option[Int] =
      var d = 0
      (0 until t.length).find { i =>
        val c = t(i)
        if c == '(' then d += 1 else if c == ')' then d -= 1
        d == 0 && t.startsWith(sym, i)
      }
    def closes(i: Int): Int =
      var d = 0
      (i until t.length).find { j => if t(j) == '(' then d += 1 else if t(j) == ')' then d -= 1; d == 0 }.getOrElse(-1)
    if t.startsWith("(") && closes(0) == t.length - 1 then parseType(t.substring(1, t.length - 1))
    else if depthZero("→").isDefined then LT.Fun(t)
    else depthZero("×") match
      case Some(i) => LT.Prod(parseType(t.take(i)), parseType(t.drop(i + 1)))
      case None if t.startsWith("List ") => LT.ListOf(parseType(t.drop(5)))
      case None if t.startsWith("Option ") => LT.OptionOf(parseType(t.drop(7)))
      case None => LT.Name(t)

  private val typeDecls: Map[String, TypeDecl] = kb.types.map(t => t.name -> t).toMap

  /** `y` occurs in `x` of type `t`, as a Lean proposition: None if a value of `t` can never hold one of
    * `target`; Left for a type FrFlow cannot unfold (a recursive one).
    */
  private def occurs(y: String, x: String, t: LT, target: LT, seen: Set[String] = Set.empty): Either[String, Option[String]] =
    val fresh = s"z${seen.size}_${x.count(_ == '.')}${x.length}'"
    def any(parts: List[Either[String, Option[String]]]): Either[String, Option[String]] =
      parts.collectFirst { case Left(w) => w }.toLeft {
        val ps = parts.collect { case Right(Some(p)) => p }
        Option.when(ps.nonEmpty)(ps.mkString("(", " ∨ ", ")"))
      }
    if t == target then Right(Some(s"$y = $x"))
    else t match
      case LT.ListOf(e)   => occurs(y, fresh, e, target, seen).map(_.map(b => s"(∃ $fresh ∈ $x, $b)"))
      case LT.OptionOf(e) => occurs(y, fresh, e, target, seen).map(_.map(b => s"(∃ $fresh, $x = some $fresh ∧ $b)"))
      case LT.Prod(a, b)  => any(List(occurs(y, s"$x.1", a, target, seen), occurs(y, s"$x.2", b, target, seen)))
      // A function can hold what it returns (or takes): what the view must list of it cannot be stated.
      case LT.Fun(text)   =>
        val names = """[A-Za-z_][\w.]*""".r.findAllIn(text).toSet
        val t = target match { case LT.Name(n) => Some(n); case _ => None }
        if t.exists(n => names(n) || names.exists(m => typeDecls.get(m).exists(_.uses.contains(n)))) then
          Left(s"the result is a function ($text), which can hold a ${t.getOrElse("")}: what the view must list of it cannot be stated")
        else Right(None)
      case LT.Name(n) => typeDecls.get(n) match
        case None => Right(None)
        case Some(_) if seen(n) => Left(s"$n is recursive")
        case Some(d) if d.ctors.size == 1 && d.ctors.head._1 == "mk" =>
          any(d.ctors.head._2.map((f, ft) => occurs(y, s"$x.$f", parseType(ft), target, seen + n)))
        case Some(d) =>
          val cases = d.ctors.map { (c, fs) =>
            val vars = fs.indices.map(i => s"${fresh}$i").toList
            (c, vars, any(fs.zip(vars).map { case ((_, ft), v) => occurs(y, v, parseType(ft), target, seen + n) }))
          }
          cases.collectFirst { case (_, _, Left(w)) => w }.toLeft {
            Option.when(cases.exists(_._3.exists(_.isDefined)))(cases.map { (c, vs, b) =>
              s"| $n.$c${vs.map(" " + _).mkString} => ${b.toOption.flatten.getOrElse("False")}"
            }.mkString(s"(match $x with ", " ", ")"))
          }

  /** That a contract's view of an invariant lists every value of the rule's type the result holds,
    * each paired with the call's input of the rule's first type (when exactly one input has it): a view
    * cannot leave out, or pair with someone else, what the result shows. Left when it cannot be stated.
    */
  def coverage(n: Node[?], inv: Node[?]): Either[String, Option[String]] =
    val ts = n.post.get.params.map(_._2)
    val rule = inv.spec.get.params.map(_._2)
    val target = parseType(rule(1))
    // About a value of the domain (a record, an opaque thing), not a number or a string, which every
    // result may hold for other reasons.
    val domain = target match
      case LT.Name(t) => typeDecls.contains(t) || nodeCtx(n).opaques.contains(t)
      case _          => false
    if !domain then Right(None) else occurs("y'", s"x${ts.size - 1}", parseType(ts.last), target).map(_.map { occ =>
      val pair = readerOf(n, inv).fold("p.2 = y'")(i => s"p.1 = x$i ∧ p.2 = y'")
      s"∀ (y' : ${rule(1)}), $occ → ∃ p ∈ ${at(n)(s"view_${inv.id}")} ${ts.indices.map(i => s"x$i").mkString(" ")}, $pair"
    }).flatMap(c => if c.isDefined && readerOf(n, inv).isEmpty && readers(n, inv).size > 1 then
        Left(s"${readers(n, inv).size} inputs are of the rule's first type: say which the pairs are about (.keeps(${inv.id}, reader = i), counting from 0)")
      else Right(c))

  /** The inputs of a contract of the rule's first type (who a call shows things to). */
  private def readers(n: Node[?], inv: Node[?]): List[Int] =
    val rule = inv.spec.get.params.map(_._2)
    n.post.get.params.map(_._2).init.zipWithIndex.filter((t, _) => parseType(t) == parseType(rule(0))).map(_._2)

  /** The input the view's pairs are about: named in `keeps`, or the only one of the rule's first type. */
  private def readerOf(n: Node[?], inv: Node[?]): Option[Int] =
    n.kept.find(_.invariant eq inv).map(_.reader).filter(_ >= 0).orElse(readers(n, inv) match { case List(i) => Some(i); case _ => None })

  /** What a node claims, from what it says (`premise`): its link, each invariant it keeps, its proven
    * implementation. `vacuous` is why the claim says nothing if it holds without the premise.
    */
  private final case class Claim(name: String, vars: String, premise: Option[String], conclusion: String, description: String,
      vacuous: String = "")

  /** The nodes on the path of a proven implementation. */
  private lazy val witnessedIds: Set[String] = kb.nodes.filter(provenImpl(_).isDefined).flatMap(kb.path).map(_.id).toSet

  private def claims(n: Node[?]): List[Claim] =
    val link = n.parent.filter(_ => n.kind == NodeKind.Refine || n.kind == NodeKind.Contract).map { p =>
      val target = if n.abs.isDefined then s"(${at(n)("abs")} m)" else "m"
      Claim("link", s"(m : ${modelType(n)})", Some(s"${at(n)("spec")} m"), s"${pat(p)("spec")} $target",
        s"Every model that meets ${n.id} meets ${p.id}.", s"vacuous: ${p.id} holds whatever ${n.id} says")
    }
    def call(ts: List[String]) = (ts.zipWithIndex.map((t, i) => s"(x$i : $t)").mkString(" "), ts.indices.map(i => s"x$i").mkString(" "))
    val keeps = formalKeeps(n).flatMap { (inv, _) =>
      val (vars, xs) = call(n.post.get.params.map(_._2))
      Claim(s"inv_${inv.id}", vars, Some(s"${at(n)("post")} $xs"),
        s"∀ p, p ∈ ${at(n)(s"view_${inv.id}")} $xs → ${at(n)(s"rule_${inv.id}")} p.1 p.2", s"Every call ${n.id} allows keeps ${inv.id}.",
        s"kept in name only: the pairs the view lists meet ${inv.id}'s rule whatever the call returns") ::
      coverage(n, inv).toOption.flatten.map(c =>
        Claim(s"cover_${inv.id}", vars, None, c, s"The view of ${inv.id} lists all the result holds of it, each with the caller.")).toList
    }
    // What service checks on every call, when the contract gives a cheap check: implied by the post.
    val localCheck = n.local.filter(_ => n.kind == NodeKind.Contract && formal(n)).map { _ =>
      val (vars, xs) = call(n.post.get.params.map(_._2))
      Claim("check", vars, Some(s"${at(n)("post")} $xs"), s"${at(n)("runCheck")} $xs",
        s"What service checks of ${n.id} on every call follows from its post: it refuses nothing the contract allows.")
    }
    val impl = provenImpl(n).map { d =>
      val (vars, xs) = call(n.post.get.params.init.map(_._2))
      Claim("impl", (assumed(n).map(_._2) :+ vars).filter(_.nonEmpty).mkString(" "), None, s"${at(n)("post")} $xs (${resolve(s"⟦${d.name}⟧")} $xs)", s"Every result of ${d.name} meets ${n.id}.")
    }
    // A proof the agent wrote may rest on a contradiction automation did not find: then something
    // must meet the node. A proven implementation at or below it is that witness (the links between
    // prove it meets the node, under the meanings fixed on the way).
    val witnessed = witnessedIds(n.id)
    val feasible = Option.when(authoredLink(n.id) && !witnessed && link.isDefined)(
      Claim("feasible", "", None, s"∃ (m : ${modelType(n)}), ${at(n)("spec")} m", s"Some model meets ${n.id}: its authored link does not rest on a contradiction."))
    // What the developer expects of every model of the node: their understanding, checked.
    val expects = Option.when(n.kind == NodeKind.Root || n.kind == NodeKind.Refine || n.kind == NodeKind.Contract)(n.expected).toList.flatten
      .zipWithIndex.map { case ((statement, _), i) =>
        Claim(s"expect_$i", s"(m : ${modelType(n)})", Some(s"${at(n)("spec")} m"), s"${at(n)(s"expected_$i")} m", statement,
          s"it holds of every model, whatever ${n.id} says: it checks nothing")
      }
    // A link proven by hand may rest on the root saying nothing, which frflow_auto cannot always see (an
    // induction does what it does not): then some model must fail the root, under the meanings fixed so far.
    val nontrivial = Option.when(authoredLink(n.id) && link.isDefined) {
      val b = binders(nodeCtx(n))
      Claim("nontrivial", "", None, s"${if b.isEmpty then "" else s"∃ $b, "}∃ (m : ${modelType(n)}), ¬ ${at(n)("rootSpec")} (${at(n)("toRoot")} m)",
        s"Some model of ${n.id} fails the root: the root says something here.")
    }
    link.toList ++ keeps ++ localCheck ++ impl ++ feasible ++ nontrivial ++ expects

  /** The contracts a node's code calls (through `contract.caller` parameters), by parameter name. */
  def callees(n: Node[?]): List[(String, Node[?])] =
    nodeCtx(n).params.flatMap(p => paramObject.get(p).flatMap(_.implementing).map(f => p -> f())).filter((_, c) => formal(c))

  /** What the code may assume of the contracts it calls: each meets its contract (a binder named `h_<p>`).
    * Only a callee with proven code is assumed: its code witnesses that the promise can be kept for
    * every call. The callee's own parameters the caller does not read are bound once, beside the
    * caller's (one store for every call), each entry being the names it binds and its binder.
    */
  private def assumed(n: Node[?]): List[(String, String)] =
    val mine = nodeCtx(n)
    val cs = callees(n).filter((_, c) => provenImpl(c).isDefined)
    val extra = cs.map((_, c) => nodeCtx(c)).foldLeft(Ctx.empty)(_ ++ _).without((mine.opaques ++ mine.params).toSet)
    Option.when(args(extra).nonEmpty)(args(extra) -> binders(extra)).toList ++ cs.map { (p, c) =>
      val ts = c.post.get.params.init.map(_._2)
      val ys = ts.indices.map(i => s"y$i").mkString(" ")
      s"h_$p" -> s"(h_$p : ∀ ${ts.zipWithIndex.map((t, i) => s"(y$i : $t)").mkString(" ")}, ${pat(c)("post")} $ys ($p $ys))"
    }

  /** What a formal node must prove: its link, the invariants it keeps, its proven implementation. */
  def obligations(n: Node[?]): List[Obligation] =
    // (`nontrivial` binds the parameters itself, with ∃.)
    claims(n).map(c => Obligation(c.name, if c.name == "nontrivial" then c.conclusion else stated(n, c.vars, c.premise, c.conclusion), c.description))
  def obligation(n: Node[?]): Option[Obligation] = obligations(n).find(_.name == "link")
  /** Obligations proven in files of their own: all but the link. */
  def extraObligations(n: Node[?]): List[Obligation] = obligations(n).filterNot(_.name == "link")

  /** A statement that, if `frflow_auto` proves it, shows the node says nothing: `fails` is the claim
    * that then fails (the link fails the node), with why.
    */
  final case class Empty(obligation: Obligation, fails: String, why: String, message: String)

  /** Each claim holding without its premise (a vacuous link; an invariant kept in name only); no model
    * meeting the node; the root holding for every model of the node, decided by an `abs` or a
    * substitution above. Each is tried by `frflow_auto`, which can miss one.
    */
  def saysNothing(n: Node[?]): List[Empty] =
    val m = s"(m : ${modelType(n)})"
    val vacuous = claims(n).filter(_.premise.nonEmpty).map { c =>
      Empty(Obligation(s"vacuous_${c.name}", stated(n, c.vars, None, c.conclusion), s"${c.description} Without ${n.id}'s own statement."),
        c.name, c.vacuous, s"${c.name} proves nothing: it holds whatever ${n.id} says")
    }
    val node = Option.when(n.kind == NodeKind.Refine || n.kind == NodeKind.Contract)(List(
      Empty(Obligation("unsat", stated(n, m, None, s"¬ ${at(n)("spec")} m"), s"No model meets ${n.id}."), "link",
        s"unsatisfiable: no model meets ${n.id}", s"${n.id} is contradictory: no model meets it, so every link below it holds and says nothing")) ++
      n.parent.filter(_.kind != NodeKind.Root).map(_ =>
        Empty(Obligation("rootTrivial", stated(n, m, None, s"${at(n)("rootSpec")} (${at(n)("toRoot")} m)"),
          s"The root holds for every model of ${n.id}, whatever ${n.id} says."), "link", s"the root holds whatever ${n.id} says",
          s"the root holds for every model of ${n.id}, whatever its spec: an abs or a substitution above decides it, so the root theorem says nothing about ${n.id}"))
    ).getOrElse(Nil)
    vacuous ++ node

  /** The seams between concerns: for each guarantee `n` relies on (see `relies`), that every state
    * the relied node's concern reaches meets it, proven from that node's root theorem. (relied node, the
    * theorem's name, its statement and proof.)
    */
  def relyChecks(n: Node[?]): List[(Node[?], String, String, String)] =
    if !formal(n) then Nil
    else n.reliedProperties.filter((o, _, r) => o != null && formal(o) && r.guarantee.body.nonEmpty).map { (o, _, r) =>
      val c = nodeCtx(o) ++ ctx(r.guarantee)
      val b = binders(c)
      val ao = args(nodeCtx(o))
      def atO(f: String) = if ao.isEmpty then q(o, f) else s"(${q(o, f)} $ao)"
      // The root's model is a function of k arguments (a run of writes, say): every state is its result.
      val rootModel = kb.rootOf(o).spec.get.params.head._2
      val k = arity(rootModel)
      val xs = (0 until k).map(i => s"x$i").mkString(" ")
      val reached = if k == 0 then s"(${atO("toRoot")} m)" else s"(${atO("toRoot")} m $xs)"
      val statement = (if b.isEmpty then "" else s"∀ $b, ") + s"∀ (m : ${modelType(o)}), ${atO("spec")} m → " +
        (if k == 0 then "" else s"∀ $xs, ") + s"(${resolve(r.guarantee.lean)}) $reached"
      val names = args(c)
      val proof = s"by\n  intro${if names.isEmpty then "" else " " + names} m h\n" +
        s"  have hr := ${q(o, "root")}${if ao.isEmpty then "" else " " + ao} m h\n" +
        (if k == 0 then "" else s"  intro $xs\n") + s"  simp only [frflow_defs] at hr ⊢\n  frflow_auto"
      (o, s"rely_${o.id}", statement, proof)
    }

  /** How many arguments a function type takes (0 for a value). */
  private def arity(t: String): Int = parseType(t) match
    case LT.Fun(text) =>
      var d = 0
      text.indices.count { i => val ch = text(i); if ch == '(' then d += 1 else if ch == ')' then d -= 1; d == 0 && text.startsWith("→", i) }
    case _ => 0

  /** The contract met by doing nothing (returning `[]` or `none`, or the input unchanged) on every
    * call, as `frflow_auto` may show: what it then leaves to the examples.
    */
  def idle(n: Node[?]): Option[(Obligation, String)] =
    if formal(n) && n.kind == NodeKind.Root then rootIdle(n) else
    Option.when(formal(n) && n.kind == NodeKind.Contract)(n.post.get.params.map(_._2)).flatMap { ts =>
      val r = ts.last
      val ins = ts.init
      val (vars, xs) = (ins.zipWithIndex.map((t, i) => s"(x$i : $t)").mkString(" "), ins.indices.map(i => s"x$i").mkString(" "))
      val nothing =
        if r.startsWith("(List ") then Some("[]" -> "returning nothing")
        else if r.startsWith("(Option ") then Some("none" -> "returning None")
        else ins.indexOf(r) match { case -1 => None; case i => Some(s"x$i" -> "returning its input unchanged") }
      nothing.map((v, what) => (Obligation("idle", stated(n, vars, None, s"${at(n)("post")} $xs $v"), s"${n.id} is met by $what."), what))
    }

  /** A root met by the model that does nothing (allows, shows or returns nothing): it says only what
    * must not happen.
    */
  private def rootIdle(n: Node[?]): Option[(Obligation, String)] =
    def strip(t: String) = if t.startsWith("(") && t.endsWith(")") && depth(t.init.tail) then t.init.tail else t
    def depth(t: String) = t.scanLeft(0)((d, c) => if c == '(' then d + 1 else if c == ')' then d - 1 else d).forall(_ >= 0)
    def arrows(t: String): List[String] =
      val out = scala.collection.mutable.ListBuffer.empty[String]; var d = 0; var from = 0
      t.indices.foreach { i =>
        if t(i) == '(' then d += 1 else if t(i) == ')' then d -= 1
        else if d == 0 && t.startsWith(" → ", i) then { out += t.substring(from, i); from = i + 3 }
      }
      (out += t.substring(from)).toList.map(_.trim)
    val parts = arrows(strip(modelType(n).trim))
    val r = parts.last
    val nothing =
      if parts.size < 2 then None
      else if r == "Prop" then Some("False" -> "allowing nothing")
      else if r.startsWith("(List ") || r.startsWith("List ") then Some("[]" -> "returning nothing")
      else if r.startsWith("(Option ") || r.startsWith("Option ") then Some("none" -> "returning None")
      else None
    nothing.map((v, what) => (Obligation("idle", stated(n, "", None, s"${at(n)("spec")} (fun ${parts.init.map(_ => "_").mkString(" ")} => $v)"),
      s"${n.id} is met by $what."), what))

